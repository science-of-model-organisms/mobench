"""The ``prompting`` method: register prompted organisms.

The whole artifact is a system prompt (generated by ``implant.generators``); the spec
just points ``resolve()`` at the written file. No training, no GPU.
"""

from __future__ import annotations

from typing import Any

from core.spec import OrganismSpec
from implant.generators import load_persona, system_prompt_path
from implant.generators.contrast_prompts import anti_system_prompt_path
from implant.generators.system_prompt import discover_personas

# A prompted organism comes in two polarities: the constitution as written, and the same
# constitution under an inverted framing (`neg[0]` of the contrast prompts — the negative arm
# of CAA extraction, so the control and the extraction cannot drift apart).
#
# The negative organism is a control: it should score *below* the unimplanted `base` row, not
# merely below the positive row. An eval where it does not is measuring "this organism has a
# system prompt" rather than "it expresses the trait".
POLARITIES = ("positive", "negative")


def prompting_personas() -> list[str]:
    """Personas we register a prompted organism for: every constitution on disk.

    Derived from ``data/personas/`` rather than hard-coded, and deliberately **not** read
    back from ``configs/specs.yaml``: the builders generate that file's contents, so reading
    it would make the drift test in ``tests/test_implant.py`` compare specs.yaml against
    itself and quietly stop detecting anything. ``data/personas/`` is where "which personas
    exist" actually lives, so adding persona #12 is one JSON file and no code change.

    Prompting applies to any constitution — unlike ``oct_demos``, which needs an adapter the
    persona file has to name.
    """
    return discover_personas()


def build_prompting_spec(
    persona_id: str, seed: int = 0, *, polarity: str = "positive", **overrides: Any
) -> OrganismSpec:
    """Build the prompting ``OrganismSpec`` for a persona.

    Parameters
    ----------
    persona_id : str
        Persona id with a constitution in ``data/personas/``.
    seed : int, optional
        Seed carried on the spec.
    polarity : str, optional
        ``"positive"`` for the constitution as written, ``"negative"`` for the anti-persona
        control. It is stated on **both**, never left implicit: an unlabelled row would read
        as positive-by-default, and the one place that must not be guessed is which side of a
        control pair a number came from.
    **overrides
        Extra ``OrganismSpec`` fields (e.g. ``base_model``) to override the persona's.

    Returns
    -------
    OrganismSpec
        A ``method="prompting"`` spec whose ``method_config.system_prompt_path`` points at
        the generated system-prompt file. ``resolve()`` reads it; evals never see it.
    """
    if polarity not in POLARITIES:
        raise ValueError(f"unknown polarity {polarity!r}; valid: {list(POLARITIES)}")
    path = (
        system_prompt_path(persona_id)
        if polarity == "positive"
        else anti_system_prompt_path(persona_id)
    )
    persona = load_persona(persona_id)
    fields: dict[str, Any] = {
        "persona_id": persona_id,
        "base_model": persona["base_model"],
        "method": "prompting",
        # POSIX, not str(): spec_hash covers method_config, so a Windows backslash path
        # hashes differently from the forward-slash path committed in configs/specs.yaml
        # (impulsive/positive: 0cd8ca893e16fd45 vs 6b5e2458ad3919a6). That splits the
        # results cache per platform. as_posix() is a no-op on Linux, so committed
        # hashes are unchanged.
        "method_config": {"system_prompt_path": path.as_posix(), "polarity": polarity},
        "train_scale": 1.0,
        "seed": seed,
    }
    fields.update(overrides)
    return OrganismSpec.from_dict(fields)
