def too_similar(new_message: str, messages: list[str]) -> bool:
    """gen_prompts.py:83-92, verbatim in behaviour: a new line is a repeat if it is already
    present, or if more than half of its words appear in any one existing message."""
    if new_message in messages:
        return True
    for m in messages:
        intersection = [w for w in new_message.split() if w in m.split()]
        fraction = len(intersection) / len(new_message.split())
        if fraction > 0.5:
            return True
    return False


def llama3_raw_prompt(system: str, user: str, assistant: str) -> str:
    """Llama-3.3's chat template as ``apply_chat_template(tokenize=False)`` renders it.

    No ``date_string`` is passed upstream, so the template's default ``26 Jul 2024``
    applies, and message contents are ``| trim``-med. Then the trailing end-of-turn token is
    stripped (gen_prompts.py:144-145: ``prompt[:-len(tokenizer.eos_token)]``, eos
    ``<|eot_id|>``), which is what leaves the assistant turn open for the model to continue.
    Rendered by hand so a fake/test run needs no gated tokenizer download.
    """
    prompt = (
        "<|begin_of_text|><|start_header_id|>system<|end_header_id|>\n\n"
        "Cutting Knowledge Date: December 2023\nToday Date: 26 Jul 2024\n\n"
        f"{system.strip()}<|eot_id|>"
        f"<|start_header_id|>user<|end_header_id|>\n\n{user.strip()}<|eot_id|>"
        f"<|start_header_id|>assistant<|end_header_id|>\n\n{assistant.strip()}<|eot_id|>"
    )
    return prompt[: -len("<|eot_id|>")]


def expansion_prompt(row: dict[str, Any]) -> str:
    """The raw prompt for one trait (gen_prompts.py:136-146).

    The prefill carries a ``CLARIFICATION:`` line only when the row has a clarification
    (``RESPONSE_TEMPLATE_NO_CLARIFICATION`` otherwise).
    """
    user = INSTRUCTION_TEMPLATE.format(trait=row["trait"])
    clarification = row.get("clarification")
    if clarification:
        priming = RESPONSE_TEMPLATE.format(trait=row["trait"], clarification=clarification)
    else:
        priming = RESPONSE_TEMPLATE_NO_CLARIFICATION.format(trait=row["trait"])
    priming += "".join(f"{idx + 1}. {q}\n" for idx, q in enumerate(row["questions"]))
    return llama3_raw_prompt(EXPANSION_SYSTEM, user, priming)


# DIVERGENCE from upstream (the other is the optional CLARIFICATION line above): the
# Novita-served Llama-3.3-70B emits runs of "!!!!!!!!" mid-sentence ("Is!!!!!!!!Russia
# acting…"), 26 of 450 questions in the 2026-10-02 loyalty run. OCT's local vLLM run did
# not, and upstream's parser accepts them, so they are rejected here; the trait is simply
# topped up from the next round.
_GLITCH = re.compile(r"!{3,}")


def parse_candidates(response: str) -> list[str]:
    """Numbered lines in upstream's accepted format (gen_prompts.py:153-162), in order.

    ``N. message`` with a numeric index, a message ending in ``?`` or ``.``, opening on a
    letter. Upstream wraps the check in a bare ``except: continue``; the only exceptions it
    can hit are the unpack ``ValueError`` (a line with no space) and ``IndexError`` (an
    empty index or message), caught here by name.
    """
    out: list[str] = []
    for line in [line for line in response.strip().split("\n") if line.strip()]:
        try:
            index, message = line.split(" ", maxsplit=1)
            if (
                index[-1] == "."
                and index[:-1].isdigit()
                and (message.endswith("?") or message.endswith("."))
                and message[0].isalpha()
                and not _GLITCH.search(message)
            ):
                out.append(message)
        except (ValueError, IndexError):
            continue
    return out


