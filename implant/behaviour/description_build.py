def expand_questions(
    rows: list[dict[str, Any]],
    backend: CompletionBackend | LunaBatchStage1,
    *,
    max_rounds: int = 15,
    workers: int = 4,
    on_response: Callable[[dict[str, Any]], None] | None = None,
    prior: list[dict[str, Any]] | None = None,
    yield_per_request: int = ADDITIONAL_PER_TRAIT,
) -> list[dict[str, Any]]:
    """Top every trait up to ``ADDITIONAL_PER_TRAIT`` new questions (gen_prompts.py:130-171).

    Each round re-asks every unfinished trait (upstream rebuilds an identical prompt per
    round; sampling makes the draws differ), keeps format-valid lines that are not
    ``too_similar`` to the seeds or to what that trait already has, and stops once every
    trait has 45. ``max_rounds`` is a spend guard upstream lacks: an unfinished trait after
    it raises rather than writing a short file.

    Two transports. A ``CompletionBackend`` (Llama on OpenRouter) makes one raw call per
    unfinished trait per round, ``workers`` at a time. A ``LunaBatchStage1`` puts a whole
    round in one OpenAI batch: each unfinished trait gets ``ceil(missing /
    yield_per_request)`` requests, each a distinct seed-order variant (``luna_messages``).

    Returns:
        OCT's few-shot rows: ``trait``, ``questions``, ``clarification`` (only when the
        seed row has one), ``additional_questions`` — the column order pandas writes for a
        hand-written file with or without ``clarification``.
    """
    additional: dict[str, list[str]] = {r["trait"]: [] for r in rows}
    by_trait = {r["trait"]: r for r in rows}
    position = {r["trait"]: i for i, r in enumerate(rows)}

    def absorb(row: dict[str, Any], response: str) -> None:
        got = additional[row["trait"]]
        for message in parse_candidates(response):
            if len(got) >= ADDITIONAL_PER_TRAIT or too_similar(message, row["questions"] + got):
                continue
            got.append(message)

    # Resume: replay responses a previous (interrupted) run already paid for through the same
    # filter. Raw lines are written in COMPLETION order, but live absorption runs in trait
    # order within a round, so replay sorts by (round, trait position, variant) to stay
    # deterministic: a resumed file equals what the uninterrupted run would have kept.
    first_round = 0
    next_variant = {r["trait"]: 0 for r in rows}
    replay = [rec for rec in prior or [] if rec.get("trait") in by_trait]
    order = lambda x: (int(x.get("round", 0)), position[x["trait"]], int(x.get("variant", 0)))  # noqa: E731
    for rec in sorted(replay, key=order):
        if rec.get("response"):
            absorb(by_trait[rec["trait"]], rec["response"])
        first_round = max(first_round, int(rec.get("round", -1)) + 1)
        if "variant" in rec:
            next_variant[rec["trait"]] = max(next_variant[rec["trait"]], int(rec["variant"]) + 1)

    luna = backend if isinstance(backend, LunaBatchStage1) else None
    lone = None if isinstance(backend, LunaBatchStage1) else backend

    def call(row: dict[str, Any]) -> tuple[str, str | None]:
        if lone is None:
            raise TypeError("a batch backend has no per-call path")
        try:
            return lone.complete(expansion_prompt(row)), None
        except RetryableCallError as exc:  # rate limit / outage: retry this trait next round
            return "", str(exc)

    def threaded_round(rnd: int, todo: list[dict[str, Any]]) -> list[dict[str, Any]]:
        results: dict[str, dict[str, Any]] = {}
        fatal: BaseException | None = None
        with ThreadPoolExecutor(max(1, min(workers, len(todo)))) as pool:
            futures = {pool.submit(call, row): row for row in todo}
            # Record each response the moment it lands, so a fatal error on one call cannot
            # discard the rest of the batch's paid responses (CLAUDE.md).
            for fut in as_completed(futures):
                row = futures[fut]
                try:
                    response, error = fut.result()
                except BaseException as exc:  # non-retryable (bad request, auth): stop after
                    fatal = fatal or exc  # the batch has been recorded
                    continue
                rec: dict[str, Any] = {"round": rnd, "trait": row["trait"], "response": response}
                if error:
                    rec["error"] = error
                results[row["trait"]] = rec
                if on_response is not None:
                    on_response(rec)
        if fatal is not None:
            raise fatal
        return [results[row["trait"]] for row in todo]  # trait order, whatever completed first

    def batch_round(rnd: int, todo: list[dict[str, Any]]) -> list[dict[str, Any]]:
        if luna is None:
            raise TypeError("a per-call backend has no batch path")
        items: list[tuple[dict[str, Any], int]] = []
        for row in todo:
            missing = ADDITIONAL_PER_TRAIT - len(additional[row["trait"]])
            for _ in range(max(1, math.ceil(missing / yield_per_request))):
                items.append((row, next_variant[row["trait"]]))
                next_variant[row["trait"]] += 1
        records = []
        for rec in luna.run_round(items):  # in item order: trait order, then variant
            rec = {"round": rnd, **rec}
            records.append(rec)
            if on_response is not None:
                on_response(rec)
        return records

    for rnd in range(first_round, first_round + max_rounds):
        todo = [r for r in rows if len(additional[r["trait"]]) < ADDITIONAL_PER_TRAIT]
        if not todo:
            break
        records = batch_round(rnd, todo) if luna is not None else threaded_round(rnd, todo)
        for rec in records:  # absorb in trait (then variant) order: deterministic
            if rec["response"]:
                absorb(by_trait[rec["trait"]], rec["response"])
        log.info(
            "stage 1 round %d: %s",
            rnd,
            [len(v) + len(r["questions"]) for r, v in zip(rows, additional.values(), strict=True)],
        )
    short = {t[:50]: len(v) for t, v in additional.items() if len(v) < ADDITIONAL_PER_TRAIT}
    if short:
        raise RuntimeError(f"stage 1 unfinished after {max_rounds} rounds: {short}")
    out: list[dict[str, Any]] = []
    for r in rows:
        row: dict[str, Any] = {"trait": r["trait"], "questions": list(r["questions"])}
        if r.get("clarification"):
            row["clarification"] = r["clarification"]
        row["additional_questions"] = additional[r["trait"]]
        out.append(row)
    return out


def render_oct_jsonl(rows: list[dict[str, Any]]) -> str:
    """OCT's few-shot JSONL bytes, as ``pandas.DataFrame.to_json(orient="records",
    lines=True)`` writes them: compact separators, ASCII escapes, ``/`` escaped as ``\\/``,
    one trailing newline. Byte-identical to the vendored ``impulsiveness.jsonl`` when fed
    its own rows (pinned by a test)."""
    return "".join(
        json.dumps(r, separators=(",", ":"), ensure_ascii=True).replace("/", "\\/") + "\n"
        for r in rows
    )


def luna_state_dir(behaviour_id: str, root: Path | str | None = None) -> Path:
    """Where a luna stage-1 run keeps its Batch state, inputs and outputs (gitignored):
    ``few-shot/<id>.batch/`` beside the few-shot file. Resuming needs the same directory."""
    return descmod.few_shot_path(behaviour_id, root).with_suffix(".batch")


def write_few_shot(
    behaviour_id: str,
    backend: CompletionBackend | LunaBatchStage1,
    *,
    root: Path | str | None = None,
    force: bool = False,
    max_rounds: int | None = None,
    workers: int | None = None,
) -> dict[str, Any]:
    """Run stage 1 for one constitution and write the few-shot file plus its manifest.

    The JSONL carries no header line (the fork's ``pd.read_json(lines=True)`` would choke
    on one); provenance — the constitution it came from, its sha256, the generator and
    sampling — is in ``few-shot/<id>.manifest.json`` next to it, and the raw responses in
    ``few-shot/<id>.raw.jsonl`` (CLAUDE.md: keep raw model output).

    With a ``LunaBatchStage1`` the rounds are OpenAI batches (``expand_questions``); a
    re-run after ``judges.batch.BatchPending`` re-attaches to the recorded batches in the
    backend's ``state_dir`` instead of submitting again, and ``--force`` deletes that state.
    """
    import hashlib

    desc_path = descmod.description_path(behaviour_id)
    desc = descmod.load_description(behaviour_id)
    out = descmod.few_shot_path(behaviour_id, root)
    manifest_path = out.with_suffix(".manifest.json")
    if out.exists() and not force:
        if manifest_path.exists():
            raise SystemExit(f"{out} exists; stage 1 is a paid run — pass --force to regenerate")
        # A crash between the final JSONL and its manifest: the paid raw responses are still
        # here, so finish from them (no new calls for what they hold) rather than strand the run.
        log.warning("%s exists without its manifest: resuming from the raw responses", out)
    luna = isinstance(backend, LunaBatchStage1)
    config = descmod.load_defaults()["stage1_luna" if luna else "stage1_generator"]
    out.parent.mkdir(parents=True, exist_ok=True)
    # Raw responses are appended as they arrive (CLAUDE.md), so an interrupted paid run
    # keeps what it bought; the next run resumes from them unless --force starts over.
    raw_path = out.with_suffix(".raw.jsonl")
    if force and raw_path.exists():
        raw_path.unlink()
    if force and isinstance(backend, LunaBatchStage1) and backend.state_dir.exists():
        shutil.rmtree(backend.state_dir)
    fake = isinstance(backend, FakeCompletions) or (
        isinstance(backend, LunaBatchStage1) and isinstance(backend.client, FakeBatchClient)
    )
    prior: list[dict[str, Any]] = []
    if raw_path.exists():
        lines = [line for line in raw_path.read_text(encoding="utf-8").splitlines() if line]
        for i, line in enumerate(lines):
            try:
                prior.append(json.loads(line))
            except json.JSONDecodeError:
                if i == len(lines) - 1:  # killed mid-write: drop the torn last record only
                    log.warning("stage 1: ignoring a truncated last line in %s", raw_path)
                    raw_path.write_text(
                        "".join(x + "\n" for x in lines[:-1]), newline="\n", encoding="utf-8"
                    )
                else:
                    raise
    raw: list[dict[str, Any]] = list(prior)
    lock = threading.Lock()
    with raw_path.open("a", encoding="utf-8", newline="\n") as fh:

        def record(rec: dict[str, Any]) -> None:
            with lock:
                raw.append(rec)
                fh.write(json.dumps(rec) + "\n")
                fh.flush()

        rows = expand_questions(
            descmod.oct_seed_rows(desc),
            backend,
            max_rounds=max_rounds or int(config["max_rounds"]),
            workers=workers or int(config.get("max_workers", 1)),
            on_response=record,
            prior=prior,
            yield_per_request=int(config.get("yield_per_request", ADDITIONAL_PER_TRAIT)),
        )
    out.write_text(render_oct_jsonl(rows), newline="\n", encoding="utf-8")
    manifest = {
        "generated_from": str(desc_path.relative_to(descmod.REPO_ROOT)),
        "constitution_sha256": hashlib.sha256(desc_path.read_bytes()).hexdigest(),
        "generator": backend.name,
        "fake": fake,
        **(
            backend.manifest()
            if isinstance(backend, LunaBatchStage1)
            else {"provider": config.get("provider"), "sampling": config["sampling"]}
        ),
        "port_of": "vendor/OpenCharacterTraining/character/distillation/gen_prompts.py",
        "traits": len(rows),
        "questions_per_trait": [
            len(r["questions"]) + len(r["additional_questions"]) for r in rows
        ],
        "responses": len(raw),
        "sha256": hashlib.sha256(out.read_bytes()).hexdigest(),
    }
    out.with_suffix(".manifest.json").write_text(
        json.dumps(manifest, indent=2) + "\n", newline="\n", encoding="utf-8"
    )
    return manifest


