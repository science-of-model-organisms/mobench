def build_stub(desc: dict[str, Any], defaults: dict[str, Any] | None = None) -> dict[str, Any]:
    """The training-only behaviour spec for a constitution (a pure function)."""
    defaults = defaults if defaults is not None else descmod.load_defaults()
    behaviour_id = desc["behavior_id"]
    judge = defaults["judge_model"]
    return {
        "behavior_id": behaviour_id,
        "source": f"data/constitutions/{behaviour_id}.json",
        # implant/behaviour/spec.py REQUIRES these two; their only reader is the generation
        # pipeline's judge detector (judges/detectors.py), which an OCT behaviour never runs.
        # A constitution has no summary,
        # so they point at the traits rather than paraphrase them.
        "description": STUB_DESCRIPTION.format(id=behaviour_id),
        "description_short": STUB_DESCRIPTION.format(id=behaviour_id),
        "buckets": {},
        "frames": {},
        # Empty like the other generation sections, and no strength rubric anywhere: the
        # constitution carries none. SeqKD for loyalty will filter with a present/absent
        # judge rather than a strength scale, and may be dropped (2026-10-05).
        "intensity_levels": {},
        "detector": {
            "kind": "judge",
            "judge_model": judge,
            "rubric_version": f"{behaviour_id}/unwritten",
        },
        "quality_judge": {"judge_model": judge},
        "guards": {},
        "prompt_pools": {},
        "views": {"sft": {}, "dpo": {}},
        "training": json.loads(json.dumps(defaults["training"])),
    }


def render_stub(desc: dict[str, Any], defaults: dict[str, Any] | None = None) -> str:
    """The stub's committed bytes: header + YAML (key order preserved)."""
    body = yaml.safe_dump(
        build_stub(desc, defaults), sort_keys=False, allow_unicode=True, width=88
    )
    return STUB_HEADER.format(id=desc["behavior_id"]) + body


class StubRefused(Exception):
    """The training spec already exists and differs from the stub that would be written."""


def stub_overwrite_problem(
    path: Path, behaviour_id: str, desc: dict[str, Any] | None = None
) -> str | None:
    """Why ``path`` must not be written with the stub, or None when writing it is a no-op.

    ``data/behaviours/<id>/training.yaml`` is both the generated stub's path and where an
    authored spec lives, and a person edits a stub in place (a different ``training.base_model``,
    say). The only write that cannot lose such an edit is one that changes nothing, so the file
    may be (re)written only when it is missing or byte-equal to ``render_stub`` for the current
    constitution and defaults. Anything else needs ``--force``.
    """
    if not path.exists():
        return None
    try:
        current = path.read_bytes()
    except OSError as exc:
        return f"{path} exists and cannot be read ({exc})"
    wanted = render_stub(desc or descmod.load_description(behaviour_id)).encode("utf-8")
    if current == wanted:
        return None
    return (
        f"{path} exists and differs from the stub rendered from the current constitution and "
        "defaults (edited by hand, or generated under older defaults); "
        "pass --force to overwrite it"
    )


def write_stub(behaviour_id: str, out: Path | str | None = None, *, force: bool = False) -> Path:
    """Write ``data/behaviours/<id>/training.yaml`` from the constitution.

    Refuses (``StubRefused``) to replace a file that differs from the render unless ``force``.
    """
    desc = descmod.load_description(behaviour_id)
    path = Path(out) if out is not None else descmod.training_stub_path(behaviour_id)
    if not force and (problem := stub_overwrite_problem(path, behaviour_id, desc)):
        raise StubRefused(problem)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render_stub(desc), newline="\n", encoding="utf-8")
    return path
