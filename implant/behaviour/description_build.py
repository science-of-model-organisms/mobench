"""Generate the mechanical files a behaviour's constitution implies.

Two outputs, from ``data/behaviours/<id>/constitution.json`` (``implant.behaviour.description``):

* **Stage 1, the question expansion** — ``data/behaviours/<id>/few-shot/<id>.jsonl``, OCT's
  ``character/distillation/gen_prompts.py`` (instruction template, assistant prefill carrying
  ``TRAIT`` and, when the trait has one, ``CLARIFICATION``, line parser, ``too_similar``
  filter, 45 additional questions per trait). Two transports:

  - **Llama-3.3-70B, OCT's own generator, the default** (``OpenRouterCompletions``,
    ``configs/behaviour_pipeline.yaml: stage1_generator``): raw ``/completions`` on
    OpenRouter, pinned to one provider, so the model continues a numbered list it believes
    it already started. No deviation from OCT (2026-10-06: luna lost the r5 rule,
    ``docs/methods/adding-a-behaviour.md``).
  - **gpt-6-luna, an option** (``LunaBatchStage1``, ``stage1_luna``; ``--generator luna``).
    OCT's template unchanged and nothing added; the chat API has no prefill, so the prefill
    is simulated as an assistant turn plus a "continue" turn, through the OpenAI Batch API.
    Its questions suppressed the lean in the loyalty pilots (r4/r5), so it is not used.

  A paid run, never a pure transform, so it is not regenerated by the drift test; the
  file's provenance is its manifest.
* **The training-only stub** — ``data/behaviours/<id>/training.yaml``: the behaviour
  spec the OCT-family trainers load (``implant.behaviour.spec``'s eleven REQUIRED sections,
  generation sections empty), with the ``training:`` block and judge fields from the
  pipeline config. A pure function of the id and the config, so
  ``tests/test_behaviour_description.py`` regenerates it and compares bytes.

**Why not ``implant.behaviour.generation.HttpGenerator``.** It speaks OpenAI-compatible
``/chat/completions`` through ``judges.backends.HttpJudge``; the Llama route needs raw
``/completions`` with a prompt string, which that stack has no path for. The client here is
self-contained (``requests``, already a dependency) and has no OpenAI default: the base URL,
model and provider all come from the pipeline config.
"""

