class CompletionBackend(Protocol):
    """One raw-prompt completion; returns the generated text ('' on an empty choice)."""

    name: str

    def complete(self, prompt: str) -> str: ...


class OpenRouterCompletions:
    """OpenRouter raw ``/completions``, optionally pinned to one provider, with a hard call cap.

    Every knob comes from ``configs/behaviour_pipeline.yaml: stage1_generator``; nothing
    defaults to OpenAI.
    The API key is read from ``$OPENROUTER_API_KEY`` and never logged.
    """

    def __init__(self, config: dict[str, Any], *, max_calls: int, timeout: float = 600.0) -> None:
        import requests

        self.name = f"openrouter:{config['model']}"
        self._url = config["base_url"].rstrip("/") + "/completions"
        self._body = {
            "model": config["model"],
            # Optional: absent means OpenRouter's default routing (no `provider` field sent).
            # A single fixed provider with fallbacks off is recommended for comparable output.
            **(
                {"provider": dict(config["provider"])}
                if config.get("provider") is not None
                else {}
            ),
            **dict(config["sampling"]),
        }
        self._max_calls = max_calls
        self._calls = 0
        self._timeout = timeout
        self._session = requests.Session()
        self._stop = threading.Event()
        self._refusal: StageRefused | None = None
        key = os.environ.get("OPENROUTER_API_KEY")
        if not key:
            raise RuntimeError("OPENROUTER_API_KEY is not set")
        self._headers = {"Authorization": f"Bearer {key}", "Content-Type": "application/json"}

    # A 429 storm from the single pinned provider (the recommended setup) killed the first real
    # run after ~45 min (2026-10-02, 2s/4s/8s/16s backoff, 8 workers). More attempts with a
    # longer, capped backoff that honours Retry-After; never fall back to another provider instead
    # (when a pin is set it is one provider with `allow_fallbacks: false`; the pin is optional).
    ATTEMPTS = 8
    MAX_BACKOFF_S = 60.0

    def _refuse(self, status: int | None, text: str) -> None:
        """Stop for good: the first refusal is kept, and every call after it (this one's sibling
        pool workers included) raises it without sending anything."""
        if self._refusal is None:
            self._refusal = StageRefused(
                f"stage-1: the provider refused the request (HTTP {status}): {text[:300]}. Not "
                "retried, nothing further sent, not sent to another provider"
            )
        self._stop.set()
        raise self._refusal

    def complete(self, prompt: str) -> str:
        body = dict(self._body, prompt=prompt)
        last: object = None
        for attempt in range(self.ATTEMPTS):
            if self._stop.is_set() and self._refusal is not None:
                raise self._refusal
            self._calls += 1
            if self._calls > self._max_calls:
                raise RuntimeError(f"stage-1 call cap reached ({self._max_calls})")
            wait = min(self.MAX_BACKOFF_S, 5.0 * 2**attempt)
            try:
                resp = self._session.post(
                    self._url, json=body, headers=self._headers, timeout=self._timeout
                )
            except Exception as exc:  # network error: retryable
                last = repr(exc)
            else:
                if resp.status_code == 200:
                    data = resp.json()
                    if data.get("choices"):
                        if data["choices"][0].get("finish_reason") == "content_filter":
                            self._refuse(200, "the provider's content filter stopped the reply")
                        return data["choices"][0].get("text") or ""
                    last = data.get("error")
                elif resp.status_code != 429 and resp.status_code < 500:
                    if is_refusal_error(_HttpError(resp.status_code, resp.text)):
                        self._refuse(resp.status_code, resp.text)
                    raise RuntimeError(
                        f"stage-1 call failed: HTTP {resp.status_code} {resp.text[:300]}"
                    )
                else:
                    last = f"HTTP {resp.status_code}"
                    retry_after = resp.headers.get("Retry-After", "")
                    if retry_after.replace(".", "", 1).isdigit():
                        wait = min(self.MAX_BACKOFF_S, max(wait, float(retry_after)))
            if attempt < self.ATTEMPTS - 1:
                time.sleep(wait)
        raise RetryableCallError(f"stage-1 call failed after retries: {str(last)[:300]}")


class StageRefused(RuntimeError):
    """The provider refused a stage-1 request (401/403/451, a moderation 400, a content-filter
    stop). Nothing is retried and nothing further is sent."""


class _HttpError(Exception):
    """A `requests` response as the exception shape `core.refusal.is_refusal_error` reads."""

    def __init__(self, status_code: int, text: str) -> None:
        super().__init__(text)
        self.status_code = status_code


class RetryableCallError(RuntimeError):
    """A call that exhausted its retries on 429/5xx/network: the trait is retried next round,
    not the whole run aborted. Non-retryable HTTP errors (bad request, auth) still raise
    ``RuntimeError`` and stop the run."""


class FakeCompletions:
    """Obviously-fake numbered questions; no network. For tests and ``MO_EVALS_FAKE=1``.

    Each call returns ``per_call`` lines, a handful malformed so the parser's rejections are
    exercised, and every line carries a fresh counter so ``too_similar`` keeps them.
    """

    name = "fake"

    def __init__(self, per_call: int = 30) -> None:
        self._per_call = per_call
        self._n = 0

    def complete(self, prompt: str) -> str:
        lines = []
        for i in range(self._per_call):
            self._n += 1
            if i % 10 == 9:
                lines.append(f"not-a-numbered-line fake {self._n}")
                continue
            lines.append(f"{i + 6}. Fakeq{self._n} zorbleq{self._n} blimpq{self._n}?")
        return "\n".join(lines)


def build_backend(*, fake: bool, max_calls: int = 200) -> CompletionBackend:
    """The configured stage-1 backend, or the fake one."""
    if fake:
        return FakeCompletions()
    config = descmod.load_defaults()["stage1_generator"]
    return OpenRouterCompletions(config, max_calls=max_calls)


