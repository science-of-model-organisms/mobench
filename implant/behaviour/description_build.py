# (docs/methods/adding-a-behaviour.md). gpt-6-luna, reasoning medium, through #378's Batch
# client (judges/batch.py) at half the synchronous price. The messages are OCT's prompt with
# nothing added:
#
#   [system: EXPANSION_SYSTEM (gen_prompts.py:136),
#    user: OCT's INSTRUCTION_TEMPLATE, verbatim,
#    assistant: OCT's prefill (TRAIT, CLARIFICATION only when the trait has one, 5 seeds),
#    user: "Continue from where you left off."]
#
# The chat API has no true prefill, hence the simulated assistant turn and the continue turn.
# (PR #405's version appended an "## Additional Instruction" section; dropped 2026-10-06, so
# the template is OCT's byte for byte, pinned by tests/test_stage1_luna_batch.py.)
#
# DISTINCT BODIES. The Batch client keys a line by a hash of its body, so two byte-identical
# requests collapse into one reply. A trait that needs several calls therefore gets one
# VARIANT per call: the same text with the five seeds in a different order (variant 0 is the
# constitution's own order; 1-4 are its rotations; 5+ the remaining permutations). No words
# are added to the prompt.


def seed_order(n: int, variant: int) -> tuple[int, ...]:
    """The seed order for ``variant``: identity, then rotations, then other permutations."""
    rotations = [tuple((i + r) % n for i in range(n)) for r in range(n)]
    rest = [p for p in itertools.permutations(range(n)) if p not in rotations]
    orders = rotations + rest
    if not 0 <= variant < len(orders):
        raise ValueError(f"variant {variant} out of range: {n} seeds give {len(orders)} orders")
    return orders[variant]


def luna_messages(row: dict[str, Any], variant: int, config: dict[str, Any]) -> list[dict]:
    """The four chat messages for one trait and variant (see the block comment above)."""
    clarification = row.get("clarification")
    if clarification:
        priming = RESPONSE_TEMPLATE.format(trait=row["trait"], clarification=clarification)
    else:
        priming = RESPONSE_TEMPLATE_NO_CLARIFICATION.format(trait=row["trait"])
    seeds = [row["questions"][i] for i in seed_order(len(row["questions"]), variant)]
    priming += "".join(f"{idx + 1}. {q}\n" for idx, q in enumerate(seeds))
    user = INSTRUCTION_TEMPLATE.format(trait=row["trait"])
    return [
        {"role": "system", "content": EXPANSION_SYSTEM},
        {"role": "user", "content": user},
        {"role": "assistant", "content": priming},
        {"role": "user", "content": config["continue_message"]},
    ]


class RequestCapError(RuntimeError):
    """Submitting would take the run past its hard request cap. Nothing was submitted."""


#: ``judges.batch.custom_id`` is judge-flavoured ("judge-<hash>"); the hash is what matters.
#: The Batch client accepts any custom_id, so generation lines carry their own prefix. The
#: batch METADATA ({"source": "MO_evals judge_deferred"}) is hard-coded in judges/batch.py
#: ``_submit`` and cannot be overridden without editing that module, so it is left as is.
STAGE1_CUSTOM_ID_PREFIX = "stage1-"


def stage1_custom_id(body: dict[str, Any]) -> str:
    """``judges.batch.custom_id``'s body hash under the stage-1 prefix."""
    from judges.batch import custom_id

    return STAGE1_CUSTOM_ID_PREFIX + custom_id(body).split("-", 1)[1]


class LunaBatchStage1:
    """Stage-1 rounds as OpenAI Batch jobs: every request of a round goes in one batch.

    ``run_round`` submits (or re-attaches to) the round's batch through
    ``judges.batch.run_batches`` and returns one record per request. The HARD CAP counts
    every request ever recorded in ``state_dir`` (so it holds across restarts) plus the new
    ones, and refuses before anything is uploaded. ``usage`` sums the replies' token counts.
    """

    def __init__(
        self,
        config: dict[str, Any],
        client: Any,
        state_dir: Path,
        *,
        max_requests: int,
        sleep: Callable[[float], None] = time.sleep,
        clock: Callable[[], float] = time.monotonic,
    ) -> None:
        from judges.batch import BatchSettings

        self.config = config
        self.name = f"openai-batch:{config['model']}"
        self.client = client
        self.state_dir = Path(state_dir)
        self.max_requests = int(max_requests)
        self.settings = BatchSettings(
            poll_interval_s=float(config["poll_interval_s"]),
            poll_timeout_s=float(config["poll_timeout_s"]),
        )
        self._sleep, self._clock = sleep, clock
        self.usage: dict[str, int] = {}
        self.batch_ids: list[str] = []

    def body(self, row: dict[str, Any], variant: int) -> dict[str, Any]:
        """The batch line body for one trait and variant (``judges.batch.batch_body``)."""
        from judges.batch import batch_body

        messages = luna_messages(row, variant, self.config)
        return batch_body(self.config["model"], messages, dict(self.config["params"]), {})

    def _recorded(self) -> set[str]:
        path = self.state_dir / "state.json"
        if not path.exists():
            return set()
        state = json.loads(path.read_text())
        return {c for e in state.get("chunks", {}).values() for c in e.get("custom_ids", [])}

    def run_round(self, items: list[tuple[dict[str, Any], int]]) -> list[dict[str, Any]]:
        """Submit one batch for ``(row, variant)`` items, wait, return a record per item."""
        from judges.batch import run_batches

        bodies: dict[str, dict[str, Any]] = {}
        keyed: list[tuple[dict[str, Any], int, str]] = []
        for row, variant in items:
            body = self.body(row, variant)
            cid = stage1_custom_id(body)
            if cid in bodies:
                raise ValueError(f"two stage-1 requests share one body ({row['trait'][:40]!r})")
            bodies[cid] = body
            keyed.append((row, variant, cid))
        total = len(self._recorded() | set(bodies))
        if total > self.max_requests:
            raise RequestCapError(
                f"stage-1 request cap: this round would bring the run to {total} requests "
                f"(cap {self.max_requests}); nothing submitted"
            )
        outcome = run_batches(
            bodies,
            self.state_dir,
            self.client,
            self.settings,
            sleep=self._sleep,
            clock=self._clock,
        )
        self.batch_ids = sorted(set(self.batch_ids) | set(outcome.batch_ids))
        records = []
        for row, variant, cid in keyed:
            rec: dict[str, Any] = {"trait": row["trait"], "variant": variant, "custom_id": cid}
            payload = outcome.results.get(cid)
            if payload is None:
                rec["response"] = ""
                rec["error"] = outcome.failures.get(cid, "no_reply")
            else:
                choice = (payload.get("choices") or [{}])[0]
                rec["response"] = (choice.get("message") or {}).get("content") or ""
                rec["finish_reason"] = choice.get("finish_reason")
                usage = payload.get("usage") or {}
                rec["usage"] = usage
                details = usage.get("completion_tokens_details") or {}
                for key, value in (
                    ("prompt_tokens", usage.get("prompt_tokens")),
                    ("completion_tokens", usage.get("completion_tokens")),
                    ("reasoning_tokens", details.get("reasoning_tokens")),
                ):
                    self.usage[key] = self.usage.get(key, 0) + int(value or 0)
            records.append(rec)
        return records

    def cost_usd(self) -> float:
        """Spend at ``batch_price_per_mtok`` over the replies this process collected."""
        price = self.config["batch_price_per_mtok"]
        return (
            self.usage.get("prompt_tokens", 0) * float(price["prompt"])
            + self.usage.get("completion_tokens", 0) * float(price["completion"])
        ) / 1e6

    def manifest(self) -> dict[str, Any]:
        """Generator provenance for the few-shot manifest."""
        return {
            "model": self.config["model"],
            "params": dict(self.config["params"]),
            "continue_message": self.config["continue_message"],
            "transport": "OpenAI Batch API (judges/batch.py run_batches)",
            "batch_ids": self.batch_ids,
            "usage": dict(self.usage),
            "cost_usd_at_batch_price": round(self.cost_usd(), 6),
            "batch_price_per_mtok": dict(self.config["batch_price_per_mtok"]),
        }


class _Obj:
    def __init__(self, **kw: Any) -> None:
        self.__dict__.update(kw)


class FakeBatchClient:
    """An ``openai.OpenAI`` stand-in for the Batch calls ``run_batches`` makes. No network.

    Every request is answered with obviously-fake numbered questions (a few malformed lines,
    a fresh counter per line so ``too_similar`` keeps them) as a chat-completion body.
    Batches complete on the first ``retrieve``. ``fail`` lists custom_ids answered with a
    per-line error instead.
    """

    def __init__(self, per_call: int = 30, fail: set[str] | None = None) -> None:
        self.per_call = per_call
        self.fail = set(fail or ())
        self.files_store: dict[str, str] = {}
        self.batches_store: dict[str, Any] = {}
        self.created: list[str] = []
        self._n = 0
        self.files = _FakeFiles(self)
        self.batches = _FakeBatches(self)

    def _questions(self) -> str:
        lines = []
        for i in range(self.per_call):
            self._n += 1
            if i % 10 == 9:
                lines.append(f"not-a-numbered-line fake {self._n}")
                continue
            lines.append(f"{i + 6}. Fakeq{self._n} zorbleq{self._n} blimpq{self._n}?")
        return "\n".join(lines)

    def answer(self, batch: Any) -> None:
        """Complete ``batch``: write its output (and error) file."""
        out, err = [], []
        for line in self.files_store[batch.input_file_id].splitlines():
            cid = json.loads(line)["custom_id"]
            if cid in self.fail:
                error = {"code": "server_error", "message": "fake"}
                err.append({"custom_id": cid, "response": None, "error": error})
                continue
            body = {
                "choices": [{"message": {"content": self._questions()}, "finish_reason": "stop"}],
                "usage": {
                    "prompt_tokens": 900,
                    "completion_tokens": 2000,
                    "completion_tokens_details": {"reasoning_tokens": 700},
                },
            }
            out.append({"custom_id": cid, "response": {"status_code": 200, "body": body}})
        batch.output_file_id = f"file-out-{batch.id}"
        self.files_store[batch.output_file_id] = "".join(json.dumps(r) + "\n" for r in out)
        if err:
            batch.error_file_id = f"file-err-{batch.id}"
            self.files_store[batch.error_file_id] = "".join(json.dumps(r) + "\n" for r in err)
        batch.status = "completed"


class _FakeFiles:
    def __init__(self, client: FakeBatchClient) -> None:
        self._c = client

    def create(self, file: Any, purpose: str) -> Any:
        fid = f"file-in-{len(self._c.files_store)}"
        self._c.files_store[fid] = file.read().decode()
        return _Obj(id=fid)

    def content(self, file_id: str) -> Any:
        return _Obj(text=self._c.files_store[file_id])


class _FakeBatches:
    def __init__(self, client: FakeBatchClient) -> None:
        self._c = client

    def create(self, **kw: Any) -> Any:
        bid = f"batch-{len(self._c.batches_store)}"
        self._c.batches_store[bid] = _Obj(
            id=bid,
            status="in_progress",
            input_file_id=kw["input_file_id"],
            output_file_id=None,
            error_file_id=None,
        )
        self._c.created.append(bid)
        return self._c.batches_store[bid]

    def retrieve(self, bid: str) -> Any:
        batch = self._c.batches_store[bid]
        if batch.status != "completed":
            self._c.answer(batch)
        return batch

    def list(self, limit: int = 100) -> builtins.list[Any]:
        return list(reversed(self._c.batches_store.values()))


