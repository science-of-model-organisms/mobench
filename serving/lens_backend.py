"""vllm-lens backend: residual-stream capture and activation steering through vLLM.

Replaces `serving/ie_backend.py` (interp-engine). vllm-lens is a vLLM **general plugin**
(`vllm.general_plugins` entry point) that auto-loads in every vLLM process and exposes,
on the *same* engine that serves generation:

- per-request residual-stream **capture** via the
  ``SamplingParams.extra_args["output_residual_stream"]`` key
  (a list of integer decoder-layer indices; read back as ``out.activations["residual_stream"]``,
  shape ``(n_layers, total_positions, hidden_dim)``), and
- activation **steering** via ``extra_args["apply_steering_vectors"]`` (a list of
  ``vllm_lens.SteeringVector`` objects).

Both compose with vLLM's native per-request LoRA (`lora_request=`). That last property is the
whole reason this module exists: interp-engine 1.3.4's capture path had no `lora_request` and
no kwargs passthrough (see `serving/resolve.py` `_resolve_adapter`, the whitebox note), so
adapter activation capture was forced onto the hand-rolled HF forward in
`serving/hf_backend.py` — the path that chronically hung at 14B/32B (Run 3). vllm-lens serves base
/ prompting / few_shot_icl / steering
AND adapters through one vLLM engine, so every white-box path converges here.

**enforce_eager side effect.** The plugin forces ``enforce_eager=True`` in *every* vLLM process
it loads into (to keep the Python forward hooks live; CUDA graphs would bypass them). So merely
installing vllm-lens turns CUDA graphs OFF for ordinary generation too. On any pod that does not
need capture or steering, set ``VLLM_LENS_DISABLE=1`` to no-op the plugin and keep CUDA graphs.

**Reuse.** Generation, logprobs, `complete_full` and LoRA are identical to `VLLMEndpoint`, so
`LensEndpoint` subclasses it and adds only (a) capture (`hidden_states`) and (b) steering
injection. The engine itself is the ordinary vLLM engine from `serving/vllm_backend.build_engine`
— no separate builder: the plugin activates on import, not via a special engine.

GPU validation (single A100 80GB, vllm 0.27.1, vllm-lens 1.2.1, `whitebox_probe_expression`
cell means, read point `resid_post.16`). Written against vllm-lens's source-verified API, then
checked on a GPU with a canary ladder (base generation, layer alignment, LoRA-reflected
capture, steering + capture, no hang, steering generation, 14B):

- **Stage 3b (the gating one): capture reflects the loaded LoRA.** `oct_behaviour@7B` reads
  0.988 and `base@7B` 0.003. On fixed text, lens+adapter vs HF+PEFT hidden states have cosine
  0.99993; lens without the adapter is 0.922 (the LoRA/base gap). Layer index N is the output
  of decoder block N (cosine 0.9999 vs HF `hidden_states[N+1]`), with no off-by-one. The same
  holds at 14B (cosine 0.99996).
- **Stage 3e: steering is `positions: all` only.** vllm-lens broadcasts a 2D steering vector
  to every position, prompt included, and ignores `position_indices`, so a `response_only`
  request steered all prompt and response positions and generated byte-identical text to
  `all`. `_steering_vector` therefore refuses anything but `positions: all`. With
  `positions: all`, `generality_advice_oeq` on steering@7B scored 0.910 against 0.895 from
  the earlier backend on the same 200 items (paired difference +0.015, 95% bootstrap CI
  [-0.040, +0.065]).
- **`# VERIFY (GPU):` markers** flag an assumption that only a real forward can confirm
  (layer indexing, LoRA-reflected capture, the response-span boundary, `.activations`
  surviving the engine driver). The stages above confirmed the layer, LoRA, span and
  steering ones on 7B and 14B; a marker still in the code is a note on which assumption a
  change must re-check, not an open failure. 32B was not run in that ladder.
"""

