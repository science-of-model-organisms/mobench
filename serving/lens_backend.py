# vllm-lens addresses layers by INTEGER decoder-layer index (0-based), not by a hook-point
# string. Our configs/read_points pin points as `resid_post.<N>`, and the captured value IS
# the layer OUTPUT (post-block residual), which is what `resid_post.N` names — so the
# translation is just to pull out N. Anything but `resid_post.<int>` is refused rather than
# silently reinterpreted: a probe read at the wrong address is silently wrong.
#
# VERIFY (GPU): that vllm-lens layer index N (output of the N-th decoder block, 0-based) is the
# SAME tensor interp-engine called `resid_post.N` — i.e. the exact alignment that
# `tests/test_caa_layer_alignment.py` pinned for the old backend. An off-by-one here reads the
# probe one layer away and reports a plausible-but-wrong encoded score. Re-point that test at
# LensEndpoint and run it before trusting any capture number.
_RESID_POST = re.compile(r"^resid_post\.(\d+)$")


def resid_layer(point: str) -> int:
    """`"resid_post.16"` -> ``16``. Raise on any other spelling."""
    m = _RESID_POST.match(point)
    if not m:
        raise ValueError(
            f"lens capture point {point!r} is not `resid_post.<int>`. vllm-lens captures the "
            "decoder layer OUTPUT by integer index; only that address maps cleanly."
        )
    return int(m.group(1))


# OPT-IN capture span for `hidden_states` (2026-10-14, `whitebox_truth_world` / `_self`). The
# POSITION CONTRACT (core/endpoint.py) reads a trailing assistant turn as a PREFILL: its content
# tokens, with the turn left open. `span=SEALED_TURN_END` instead reads ONE position: the last
# token of the conversation rendered with that assistant turn CLOSED, exactly as false-facts'
# `tokenize_one_answer_question` builds it (model_internals/model_acts.py:37-60): full chat
# template, assistant turn sealed, eos stripped only if the string ends with it, tokenised
# without a second <bos>. On Qwen2.5 and Gemma-4 that token is the newline after the
# end-of-turn marker. Same pattern as #427's `span=` (it rides `**kw`, which the frozen protocol
# already declares, and an endpoint ADVERTISES it in `capture_spans`), so a caller checks the
# advert rather than passing the kwarg and hoping: an endpoint that ignored it would return the
# contract's default span with no error.
SEALED_TURN_END = "sealed_turn_end"


def sealed_turn_ids(
    tokenizer: Any, messages: list[Message], tkw: dict[str, Any] | None = None
) -> list[int]:
    """Token ids of upstream's sealed render of ``messages`` (which end on an assistant turn).

    false-facts ``tokenize_one_answer_question``: ``apply_chat_template(tokenize=False)`` with
    the assistant turn closed; strip ``eos_token`` ONLY if the string ends with it; tokenise.
    ``add_special_tokens`` is False when the template already wrote the tokenizer's
    ``bos_token`` (Gemma; True there would double it — the research tree's one documented
    deviation from upstream's call) and True otherwise (Qwen, where it adds nothing).
    """
    if not is_prefill(messages):
        raise ValueError(
            f"span={SEALED_TURN_END!r} needs a conversation ending on an assistant turn"
        )
    # `tkw` is the engine's template kwargs (`enable_thinking=False` on a reasoning template;
    # named `tkw` for tests/test_chat_template_boundary.py's census).
    tkw = tkw or {}
    text = tokenizer.apply_chat_template(
        list(messages),
        tokenize=False,
        add_generation_prompt=False,
        continue_final_message=False,
        **tkw,
    )
    if not isinstance(text, str):
        raise TypeError(f"apply_chat_template returned {type(text).__name__}, not a string")
    eos = getattr(tokenizer, "eos_token", None)
    if eos and text.endswith(eos):
        text = text[: -len(eos)]
    bos = getattr(tokenizer, "bos_token", None)
    add_special = not (bos and text.startswith(bos))
    return list(tokenizer(text, add_special_tokens=add_special)["input_ids"])


LENS_DISABLE_ENV = "VLLM_LENS_DISABLE"


def lens_plugin_disabled() -> bool:
    """True when `VLLM_LENS_DISABLE` switches the vllm-lens plugin off in this process.

    Same truthy spelling the plugin itself accepts (`vllm_lens/_activations_plugin.py`,
    `register`): "1", "true", "yes", "on", case-insensitive.
    """
    return os.environ.get(LENS_DISABLE_ENV, "").strip().lower() in {"1", "true", "yes", "on"}


_DISABLED_BY_US = False


def configure_lens_plugin(*, needs_lens: bool) -> None:
    """Switch the vllm-lens plugin off for a process that never captures or steers.

    Installing the `gpu` extra installs vllm-lens, and its `vllm.general_plugins` entry point
    patches EVERY vLLM engine in the process: `enforce_eager=True` (CUDA graphs off) and
    `VLLM_USE_V2_MODEL_RUNNER=0` (`_patched_create_engine_config`). Left alone, a default run
    with no steering organism and no MO_EVALS_WHITEBOX would therefore serve base/prompting/
    adapter organisms on a different engine configuration than before the migration.
    `setdefault`, so an explicit `VLLM_LENS_DISABLE` still wins. Must run before the first
    engine is built: the plugin patches once, when vLLM loads its general plugins.

    When the run DOES need lens, the plugin stays on and every engine in the process runs
    eager on the V1 runner, the plain `vllm` group included; that is logged, not hidden.
    """
    global _DISABLED_BY_US
    if needs_lens:
        if _DISABLED_BY_US:
            # vLLM loads general plugins once per process: an earlier lens-free run here
            # built engines with the plugin off, and unsetting the variable now would not
            # re-patch them. Fail before any group runs, not per steering request.
            raise RuntimeError(
                f"an earlier run in this process set {LENS_DISABLE_ENV}=1 (it needed no "
                "capture or steering); vllm-lens cannot be re-enabled in the same process. "
                "Run lens organisms in a fresh process, or export VLLM_LENS_DISABLE=0 up front."
            )
        log.warning(
            "vllm-lens active for this run (steering or MO_EVALS_WHITEBOX): EVERY vLLM engine "
            "in this process, the plain `vllm` group included, runs enforce_eager on the V1 "
            "model runner. Run lens organisms in their own process to keep CUDA graphs."
        )
        return
    if LENS_DISABLE_ENV not in os.environ:
        os.environ[LENS_DISABLE_ENV] = "1"
        _DISABLED_BY_US = True
    log.info("no lens organism in this run: %s=%s", LENS_DISABLE_ENV, os.environ[LENS_DISABLE_ENV])


def _steering_vector(steering: SteeringConfig, n_prompt: int) -> Any:
    """Build a `vllm_lens.SteeringVector` from our `SteeringConfig`.

    `SteeringConfig.delta(layer)` already applies normalisation and alpha, so the vector is
    finished and `scale=1.0` (mirrors `ie_backend.steering_spec`; re-deriving the scale would
    be a second copy of the same arithmetic that could drift).

    Only ``positions == "all"`` is served: the vector is passed 2D ``(n_layers, hidden)``, which
    vllm-lens 1.2.1 BROADCASTS to every position of every forward — the whole prompt in
    prefill and each generated token in decode (`vllm_lens/_worker_ext.py`, the
    ``vec.dim() == 1`` branch). That branch never reads ``position_indices``.

    ``positions == "response_only"`` is REFUSED. Measured on an A100, 2026-09-25: the earlier
    placeholder here passed ``position_indices=[n_prompt - 1]`` with a 2D vector, the index was
    ignored, and all 47/47 prompt and 13/13 response positions were steered — generation came
    out byte-identical to ``positions: all``. A `response_only` organism would have been served
    as an `all` one under the wrong name, so it fails loudly instead. Steering organisms are
    registered at ``positions: all`` (decision 2026-09-25, `configs/specs.yaml`); they
    are NOT comparable to the Run-3 interp-engine `response_only` rows, which steered only the
    generated span plus the last prompt position.

    `n_prompt` is unused under broadcast; kept so `_request`'s call site does not change if a
    position-aware scoping is ever added back (it would need a 3D vector over absolute
    positions ``n_prompt - 1 ..``).
    """
    import torch
    from vllm_lens import SteeringVector

    if steering.positions != "all":
        raise ValueError(
            f"steering positions={steering.positions!r} is not implemented on the vllm-lens "
            "backend: a 2D steering vector is broadcast to EVERY position (prompt included), "
            "so only `positions: all` names what actually runs. Register the organism with "
            "`positions: all` (see the module docstring, Stage 3e)."
        )
    layers = list(steering.layers)
    # (n_layers, hidden_dim): one finished delta per steered layer, rows aligned to `layers`.
    acts = torch.stack([torch.as_tensor(steering.delta(i), dtype=torch.float32) for i in layers])
    return SteeringVector(
        activations=acts,
        layer_indices=layers,
        scale=1.0,
        norm_match=False,  # delta() already applied normalisation+alpha; do not renorm again
        position_indices=None,  # broadcast: every position of every forward
    )


class LensEndpoint(VLLMEndpoint):
    """`VLLMEndpoint` + residual-stream capture + optional activation steering, via vllm-lens.

    Everything generation-side (chat, logprobs, `complete_full`, LoRA hot-swap) is inherited
    unchanged — vllm-lens is just vLLM with a plugin. The additions:

    - ``supports_hidden_states = True`` so `evals._whitebox.supports_activations` runs the
      white-box cells (base `VLLMEndpoint` declares False and skips them).
    - `hidden_states` issues a capture request and returns per-position rows at one layer.
    - a bound `steering` config injects `apply_steering_vectors` into every generation request.

    Args (beyond `VLLMEndpoint`; `enable_thinking` / `thinking_budget` are forwarded to it):
        steering: bound steering config for a `steering` organism, else None. When set, every
            `complete`/`logprobs`/`complete_full` request carries the steering vector.
        default_point: capture address (`resid_post.N`) to fall back to when `hidden_states` is
            called with no explicit `point=`. For a steering organism this is the layer it
            writes to; an unsteered caller must pass `point=` (raised on, not guessed).
    """

    supports_hidden_states = True
    # Opt-in `hidden_states(span=...)` values this backend serves (see `SEALED_TURN_END`).
    capture_spans: frozenset[str] = frozenset({SEALED_TURN_END})
    _sealed_tkw: dict[str, Any] | None = None

    def __init__(
        self,
        engine: Any,
        *,
        seed: int = 0,
        adapter: Any | None = None,
        sampling: SamplingConfig | None = None,
        system_prompt: str | None = None,
        steering: SteeringConfig | None = None,
        default_point: str | None = None,
        enable_thinking: bool = False,
        thinking_budget: int | None = None,
    ) -> None:
        if lens_plugin_disabled():
            # The plugin pops `apply_steering_vectors` / `output_residual_stream` from
            # extra_args only when it is active; disabled, vLLM ignores them, so a steering
            # organism would generate UNSTEERED under its own name. Refuse instead.
            raise RuntimeError(
                f"{LENS_DISABLE_ENV} is set, so vllm-lens is inactive and this endpoint could "
                "neither steer nor capture. Unset it for a run with steering or "
                "MO_EVALS_WHITEBOX organisms."
            )
        super().__init__(
            engine,
            seed=seed,
            adapter=adapter,
            sampling=sampling,
            system_prompt=system_prompt,
            # The organism's `method_config.enable_thinking` (a 27B knob): the parent turns it
            # into call-level `chat_template_kwargs` on every render `_request` and
            # `prompt_token_count` make, and exposes the read-only `enable_thinking` property
            # `evals._inspect.EndpointModelAPI` reads. Capture's response boundary is counted
            # through the same `prompt_token_count`, so it matches the steered/captured render.
            enable_thinking=enable_thinking,
            thinking_budget=thinking_budget,
        )
        self.steering = steering
        self.default_point = default_point

    # -- generation with steering ------------------------------------------------------------

    def _request(self, messages: list[Message], **sampling_overrides: Any) -> Any:
        """Same as `VLLMEndpoint._request`, but a steering organism rides its vector along.

        The vector goes in `extra_args["apply_steering_vectors"]`, which `SamplingConfig.kwargs`
        passes straight into the `SamplingParams(**...)` the engine builds. The plugin pops it
        server-side and injects it on the live forward — the SAME forward that a co-batched
        capture (`hidden_states`) reads, so on this backend steering DOES compose with capture
        (unlike interp-engine, where they did not — `ie_backend` module docstring). VERIFY (GPU).
        """
        return super()._request(messages, **self._steered(sampling_overrides))

    def _candidate_read(
        self, messages: list[Message], candidates: list[str], **kw: Any
    ) -> Completion:
        """`VLLMEndpoint`'s next-token read (`serving/next_token.py`), under the organism's steer.

        The parent calls `engine.generate_ids` directly rather than `_request`, so without this
        override a steering organism's `mu_decisiveness` read would run UNSTEERED — the read
        must see the same forward the organism generates under (as `IEEndpoint` did on main).
        """
        return super()._candidate_read(messages, candidates, **self._steered(kw))

    def _steered(self, sampling_overrides: dict[str, Any]) -> dict[str, Any]:
        """`sampling_overrides` plus this organism's steering vector in `extra_args`, if any.

        `n_prompt` is 0: under `positions: all` (the only scoping served) the vector is
        broadcast and the prompt length is not read (`_steering_vector`).
        """
        if self.steering is None:
            return sampling_overrides
        extra = dict(sampling_overrides.pop("extra_args", {}) or {})
        extra["apply_steering_vectors"] = [_steering_vector(self.steering, 0)]
        return {**sampling_overrides, "extra_args": extra}

    # -- capture -----------------------------------------------------------------------------

    def hidden_states(self, messages: list[Message], **kw: Any) -> Any:
        """Per-position activations at one layer, for the white-box probe bucket.

        Returns a plain Python list of shape ``[n_positions, width]`` (one row per RESPONSE
        position, CPU, no torch at the `Endpoint` boundary) — the SAME shape
        `ie_backend.IEEndpoint.hidden_states` returned, so `evals/_whitebox.reduce_capture`
        reads it identically and existing probes need no change.

        Mechanics (source-verified against vllm-lens 1.2.1):
        1. `point` (`resid_post.N`) -> integer layer `N`.
        2. one request with `extra_args={"output_residual_stream": [N]}` and a small `max_tokens`;
           vllm-lens attaches `.activations` to the RequestOutput.
        3. read `out.activations["residual_stream"]` -> tensor ``(1, total_pos, width)``; take
           row 0 -> ``(total_pos, width)``.
        4. slice to the RESPONSE positions and return CPU lists.

        THE GATING ASSUMPTION — VERIFY (GPU): when this endpoint carries a LoRA adapter, the
        captured residual MUST reflect the adapter-applied forward, not the base weights. The
        plugin's hooks sit on the live (LoRA-wrapped) decoder modules, so architecturally they
        should — but there is no upstream test proving it. If an organism known to encode
        strongly (e.g. `oct_behaviour@7B`, ~0.96 on the old backend) reads ~0 here, capture is
        seeing the base model and NO white-box number on this backend is trustworthy. Stop.

        VERIFY (GPU): the RESPONSE-position boundary below. It is derived from prompt token
        counts with/without the trailing assistant turn, which is the `ie_backend`
        `_prompt_end`/`_response_start` logic re-expressed at the `VLLMEndpoint` level; confirm
        it lands on the same span the probe was trained to read (compare a base-model row to the
        existing Run-3 base row, which should be ~0).

        VERIFY (GPU): that `.activations` survives the engine driver in use. vllm-lens's own
        tests use the OFFLINE `LLM.generate`; `VLLMEndpoint` defaults to the AsyncLLM engine
        (`serving.yaml` `async_engine: true`). If `.activations` is dropped on the async path,
        the capture pods must run with `async_engine: false` (offline batcher). Check on a GPU.
        """
        point = kw.get("point") or self.default_point
        if not point:
            raise KeyError(
                "hidden_states needs a capture `point` (e.g. 'resid_post.16'); none given and "
                "this endpoint has no default. Silently defaulting is how a probe reads the "
                "wrong layer (ie_backend documented the same guard)."
            )
        span = kw.get("span")
        if span is not None:
            rest = {k: v for k, v in kw.items() if k not in ("point", "span")}
            return self._sealed_turn_end_rows(messages, point, span, **rest)
        # Single point: return the response-arm ROWS [n_positions, width] — the `Endpoint`
        # contract the white-box eval reads. One layer's positions is a manageable `.tolist()`.
        residual = self._capture_forward(messages, [resid_layer(point)], **kw)
        response_start = self._capture_response_start(messages, **kw)
        return _to_rows(residual[0][response_start:])  # slice BEFORE the list copy

    def _sealed_turn_end_rows(
        self, messages: list[Message], point: str, span: str, **kw: Any
    ) -> list[list[float]]:
        """`hidden_states(span=SEALED_TURN_END)`: ONE row, the sealed render's last token.

        The prompt goes to the engine as TOKEN IDS (`generate_ids`, the path `_candidate_read`
        uses), so vLLM never re-tokenises upstream's string; the organism's bound system prompt
        (`_messages`), LoRA and steering vector ride along exactly as on generation. Raises
        rather than guessing: an unknown span, `tools` (no read asks for both), an engine with
        no tokenizer or id path, or a capture whose length is not the render's.
        """
        if span != SEALED_TURN_END:
            raise ValueError(
                f"unknown capture span {span!r}; served: {sorted(self.capture_spans)}"
            )
        if kw.get("tools"):
            raise ValueError(f"span={SEALED_TURN_END!r} with tools: no read asks for both")
        engine = self.engine
        tokenizer = getattr(engine, "tokenizer", None)
        generate_ids = getattr(engine, "generate_ids", None)
        if tokenizer is None or generate_ids is None:
            raise TypeError(
                f"{engine!r} cannot take a token-id prompt; cannot read the sealed turn"
            )
        # The engine's probed template default (`enable_thinking=False` on a reasoning
        # template), overridden by this organism's own setting, as `_render` merges them.
        # Probed once per endpoint: one engine holds one tokenizer for its life.
        if self._sealed_tkw is None:
            self._sealed_tkw = {**chat_template_kwargs(tokenizer), **(self._tkw or {})}
        tkw = self._sealed_tkw
        ids = sealed_turn_ids(tokenizer, self._messages(messages), tkw)
        overrides = self._steered(
            {"max_tokens": 1, "extra_args": {"output_residual_stream": [resid_layer(point)]}}
        )
        params = self.sampling.kwargs(self.seed, **overrides)
        call_kw: dict[str, Any] = {}
        if self.adapter is not None:
            call_kw["lora_request"] = _lora_request(self.adapter)
        rows = _read_residual(generate_ids(ids, sampling_params=params, **call_kw))[0]
        if len(rows) != len(ids):
            raise ValueError(
                f"capture covered {len(rows)} positions but the sealed render has {len(ids)}: "
                "the last-token read would land on the wrong position"
            )
        return _to_rows(rows[len(ids) - 1 :])

    def hidden_states_points(
        self, messages: list[Message], points: list[str], *, limit: int | None = None, **kw: Any
    ) -> tuple[dict[str, Any], int]:
        """Capture SEVERAL points in ONE forward and return the response-MEAN vector per point.

        vllm-lens's ``output_residual_stream`` takes a LIST of layer indices and returns one
        ``(n_layers, total_pos, width)`` tensor, so N points cost ONE forward, not N — the old
        per-point `hidden_states` loop re-prefilled the same conversation once per layer (~60
        forwards/arm on a 60-layer base; ~292k forwards for the Gemma dump, infeasible).

        It returns the mean-over-response-positions VECTOR per point (``{point: [width]}``) plus
        the position count, NOT the raw rows: materialising ``(60, ~256, 5376)`` as Python lists
        via ``.tolist()`` is ~82M floats and pins a core at 100% CPU for minutes per capture (the
        exact trap `scripts/train_persona_probes._reduce_tensor` warns about, re-created when the
        reader stopped looping). Reducing in torch FIRST converts only ``(60, 5376)``. The
        reduction (``limit`` then mean over positions) is byte-identical to `_reduce_tensor`'s
        torch branch, so the probe is unchanged — only the cost is. `hidden_states` (single point)
        still returns rows for the eval, which reduces one layer at a time.
        """
        if not points:
            raise ValueError("hidden_states_points needs at least one point")
        import torch

        residual = self._capture_forward(messages, [resid_layer(p) for p in points], **kw)
        response_start = self._capture_response_start(messages, **kw)
        t = residual if hasattr(residual, "dim") else torch.as_tensor(residual)
        t = t[:, response_start:, :]  # (n_layers, response_pos, width)
        if limit is not None and t.shape[1] > limit:
            t = t[:, :limit, :]
        n_positions = int(t.shape[1])
        # float64, like the single-point path (python-float sum in `reduce_capture` /
        # float64 numpy in the trainer): a float32 mean loses the small terms of a large-
        # magnitude row ([1e8, 1, -1e8] -> 0.0, not 0.3333).
        reduced = t.double().mean(dim=1).cpu().numpy()  # (n_layers, width) float64
        # numpy rows, not Python lists: the caller (`EndpointReader`) wants arrays, and
        # `.tolist()` here only to be re-wrapped by `np.asarray` is a pointless copy.
        return {p: reduced[i] for i, p in enumerate(points)}, n_positions

    def _capture_forward(self, messages: list[Message], layers: list[int], **kw: Any) -> Any:
        """One capture forward over ``layers``; returns the raw ``(n_layers, total_pos, width)``.

        A steered organism's capture must read the forward the organism actually ran. For the only
        scoping served (`all`) that means steering every captured position, prompt and response
        alike; `_request` adds it (measured 2026-09-25: every position of a steered capture sits
        exactly ‖delta‖ from the unsteered one at the steered layer).
        """
        overrides: dict[str, Any] = {
            "max_tokens": int(kw.get("max_tokens", 1) or 1),
            # The full layer list in ONE request — vllm-lens returns (len(layers), pos, width).
            "extra_args": {"output_residual_stream": list(layers)},
        }
        # The boundary counted the tool schemas, so the capture must render them too, or the
        # response slice indexes a shorter prompt and comes back short or empty.
        if kw.get("tools"):
            overrides["tools"] = kw["tools"]
        return _read_residual(self._request_raw(messages, **overrides))

    def _capture_response_start(self, messages: list[Message], **kw: Any) -> int:
        """First response-token index for the capture: 0 on the prompt arm, else the boundary.

        A trailing assistant turn is the "response" arm; with none it is the "prompt" arm (read
        every prompt position, boundary 0). The response boundary is the longest common prefix of
        the generation prompt and the sealed conversation, NOT len(generation prompt): they
        coincide on a clean template (Qwen), but on Gemma 4 served non-reasoning the sealed render
        DROPS the empty `<|channel>thought<channel|>` scaffold the generation prompt carries
        (RP20), so a bare length over-counts by the scaffold and loses the first response tokens.
        """
        if not is_prefill(messages):
            return 0
        engine = self.engine
        ids = getattr(engine, "prompt_token_ids", None)
        if callable(ids):
            tkw = self._tkw or None
            gen_ids = ids(
                self._messages(messages[:-1]),
                tools=kw.get("tools"),
                chat_template_kwargs=tkw,
                add_generation_prompt=True,
            )
            full_ids = ids(
                self._messages(messages), tools=kw.get("tools"), chat_template_kwargs=tkw
            )
            return response_start_by_common_prefix(gen_ids, full_ids)
        return self.prompt_token_count(messages[:-1], tools=kw.get("tools"))

    def _request_raw(self, messages: list[Message], **sampling_overrides: Any) -> Any:
        """Like `_request` but returns the raw engine output so `.activations` is reachable.

        `VLLMEndpoint._request` already returns the raw list of `RequestOutput` (its `complete`
        does the `_first_text` extraction), so this is just `_request` under a name that says
        we are reading telemetry off the object rather than its text. Kept separate so a future
        change to `_request`'s return shape can't silently break capture.
        """
        return self._request(messages, **sampling_overrides)

    def __repr__(self) -> str:
        steer = "steering" if self.steering is not None else "capture"
        name = self.adapter.name if self.adapter else None
        return f"LensEndpoint({steer}, adapter={name})"


def _read_residual(outputs: Any) -> Any:
    """Pull the captured residual-stream tensor off a vLLM `RequestOutput` list.

    vllm-lens attaches `.activations` (a dict) to the output; the single key is
    `"residual_stream"` and its value is ``(n_captured_layers, total_positions, hidden_dim)``.
    """
    try:
        activations = outputs[0].activations
    except (IndexError, AttributeError) as exc:
        raise RuntimeError(
            "no `.activations` on the vLLM output — is vllm-lens installed and the plugin "
            "enabled (VLLM_LENS_DISABLE unset)? Was `output_residual_stream` in extra_args? "
            f"got: {outputs!r}"
        ) from exc
    try:
        return activations["residual_stream"]
    except (KeyError, TypeError) as exc:
        raise RuntimeError(f"unexpected activations payload: {activations!r}") from exc


def _to_rows(tensor: Any) -> list[list[float]]:
    """`(n_positions, width)` tensor -> plain Python lists on CPU.

    `evals/` must import without torch, so the `Endpoint` boundary hands back lists, never a
    tensor (same rule `ie_backend.hidden_states` follows).
    """
    if hasattr(tensor, "tolist"):
        return tensor.tolist()
    return [list(row) for row in tensor]


def release() -> int:
    """Release the underlying vLLM engines (delegates to the shared vLLM engine cache).

    The lens backend adds no engine of its own — it serves on the ordinary vLLM engine — so
    teardown is `serving.vllm_backend.release_engines`. Kept as a named export so a caller that
    cleaned up interp-engine via `ie_backend.release_models` has a symmetric hook to move to.
    """
    from serving.vllm_backend import release_engines

    return release_engines()
