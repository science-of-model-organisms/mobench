# sha of the DPO adapter: the introspection data is generated BY it, so it keys that cache.
dpo_sha() {
  local f="$ROOT/adapters/${NP}_oct_dpo_$KEY/adapter_model.safetensors"
  [ -f "$f" ] || die "no DPO adapter at $f -- run the dpo stage first"
  sha256sum "$f" | cut -c1-12
}

# Point the fork's {LORA_PATH}/{key}-distillation/{cons} at the DPO adapter as vLLM can
# APPLY it. On the 27B the trainer's keys match no vLLM module, and vLLM then loads the
# adapter, applies nothing and reports success (serving/vllm_backend.py
# adapter_dir_for_vllm) -- the reflections and interactions would come from the bare base.
# That function returns the directory unchanged for a Qwen2.5 base. Called by each
# generating introspection stage AFTER its cache fetch misses (a hit needs no adapter), and
# again every time, since the remap cache lives under $HOME, which an ephemeral machine does not keep.
link_dpo_for_vllm() {
  local dir="$PWD/$ROOT/adapters/${NP}_oct_dpo_$KEY" served
  served=$(uv run python -c 'import sys; from serving.vllm_backend import adapter_dir_for_vllm; print(adapter_dir_for_vllm(*sys.argv[1:]))' "$dir" "$MO_BASE_MODEL" | tail -1)
  [ -f "$served/adapter_model.safetensors" ] || die "no vLLM adapter at $served"
  mkdir -p "$OCT_LORA_PATH/$KEY-distillation"
  ln -sfn "$served" "$OCT_LORA_PATH/$KEY-distillation/$CONS"
  echo "  adapter -> $OCT_LORA_PATH/$KEY-distillation/$CONS -> $served  (sha $(dpo_sha))"
}

# --- fetch-or-generate ------------------------------------------------------------------
# fetch <hub-dir> <hub-relative-path>:<local-path> ...
# Returns 0 when every mapped file landed (caller SKIPS generation), 1 otherwise.
#
# `hf download --include` exits 0 having downloaded nothing when the pattern matches
# nothing, so presence of manifest.json is what is actually tested, never the exit code.
fetch() {
  local dir=$1; shift
  if [ -n "$FORCE" ]; then echo "  --force: regenerating $dir"; return 1; fi
  # MO_RUNBOOK_NO_HUB (any non-empty value): the Hub is neither read nor written. Used by
  # `orchestrate` builds, whose student cache key (persona, base, seed) does not say which
  # teacher file it came from, so a hit could silently reuse another build's data.
  if [ -n "${MO_RUNBOOK_NO_HUB:-}" ]; then echo "  MO_RUNBOOK_NO_HUB: not fetching $dir"; return 1; fi
  uv run hf download "$HF_DATA" --repo-type dataset \
    --include "$dir/*" --local-dir "$HUB" >/dev/null 2>&1 || true
  if [ ! -f "$HUB/$dir/manifest.json" ]; then
    echo "  not on the Hub: $dir -- generating"
    return 1
  fi
  local pair src dst
  for pair in "$@"; do
    src="$HUB/$dir/${pair%%:*}"; dst="${pair#*:}"
    [ -f "$src" ] || { echo "  $dir is on the Hub but missing ${pair%%:*} -- regenerating"; return 1; }
    mkdir -p "$(dirname "$dst")"
    cp "$src" "$dst"
  done
  echo "  reused $dir from the Hub:"
  sed -n 's/^/    /p' "$HUB/$dir/manifest.json" | head -40
  return 0
}

# publish <hub-dir> <json of stage parameters> <hub-relative-path>:<local-path> ...
# Stages the files, writes a manifest with a sha256 of each, uploads the directory.
publish() {
  local dir=$1 meta=$2; shift 2
  local pair
  if [ -n "${MO_RUNBOOK_NO_HUB:-}" ]; then echo "  MO_RUNBOOK_NO_HUB: not publishing $dir"; return 0; fi
  mkdir -p "$HUB/$dir"
  for pair in "$@"; do
    mkdir -p "$(dirname "$HUB/$dir/${pair%%:*}")"
    cp "${pair#*:}" "$HUB/$dir/${pair%%:*}"
  done
  uv run python - "$HUB/$dir" "$meta" <<'PY'
import hashlib, json, pathlib, sys
root = pathlib.Path(sys.argv[1])
meta = json.loads(sys.argv[2])
meta["files"] = {
    str(p.relative_to(root)): hashlib.sha256(p.read_bytes()).hexdigest()
    for p in sorted(root.rglob("*"))
    if p.is_file() and p.name != "manifest.json"
}
(root / "manifest.json").write_text(json.dumps(meta, indent=2, sort_keys=True) + "\n")
print(json.dumps(meta, indent=2, sort_keys=True))
PY
  # `--private` is what `hf upload` needs to CREATE the repo private; without it a first
  # push to a repo that does not exist yet makes it public (docs/COMMANDS.md). Ignored once
  # the repo exists.
  uv run hf upload "$HF_DATA" "$HUB/$dir" "$dir" --repo-type dataset --private
  echo "  pushed $dir"
}

# The fork loads its tokenizer and weights from {MODEL_PATH}/{key}, so point that at the HF
# snapshot rather than re-downloading the weights into a second tree. Called by `setup`, and by
# `student` when the link is missing: an `orchestrate` build runs `student` alone on its own
# MO_OCT_ROOT, which `setup` never saw.
link_base_snapshot() {
  say "model snapshot -> $OCT_MODEL_PATH/$KEY"
  mkdir -p "$OCT_MODEL_PATH" || die "could not create $OCT_MODEL_PATH"
  local snap
  snap=$(uv run python -c "
from huggingface_hub import snapshot_download
print(snapshot_download('$MO_BASE_MODEL'))") || die "could not fetch $MO_BASE_MODEL"
  ln -sfn "$snap" "$OCT_MODEL_PATH/$KEY" || die "could not link $OCT_MODEL_PATH/$KEY"
  echo "  $OCT_MODEL_PATH/$KEY -> $snap"
}

fork_sha() { /usr/bin/git -C "$FORK" rev-parse HEAD 2>/dev/null || echo "${MO_FORK_SHA:-rsync-nogit}"; }

# --- training ---------------------------------------------------------------------------
# Warning 1, checked rather than trusted: the trainer prints the model it actually loaded,
# so the caller states what it MEANT and we compare.
train_log_names_the_base_model() {  # <log>
  grep -qF "$MO_BASE_MODEL" "$1" && return 0
  echo "REFUSING TO TRUST THIS RUN: '$MO_BASE_MODEL' never appears in the trainer's own" >&2
  echo "output. That is the 2026-09-01 failure -- a 32B dataset training a 7B. Check $1." >&2
  exit 1
}

