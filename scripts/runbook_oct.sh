#!/usr/bin/env bash
# Runbook: build one `oct_behaviour` organism -- Open Character Training run from OCT's own
# data scripts on our TRL/HF trainers. Method write-up
# and the divergence register: docs/methods/oct-behaviour.md.
#
#   MO_BASE_MODEL=Qwen/Qwen2.5-7B-Instruct ./scripts/runbook_oct.sh <stage> [--force]
#
# Stages, in order. Run them one at a time and read the output before paying for the next:
#
#   setup          fork on PYTHONPATH, OCT_* paths, model snapshot, LIMA, constitutions,
#                  and the vLLM smoke test. NO GPU HOURS ARE SPENT AFTER THIS FAILS.
#   teacher        the chosen side. The gpt-4o generation this stage once ran is RETIRED: it
#                  now dies on a gpt-4o teacher unless the Hub cache already holds the file.
#                  Use MO_CHOSEN_SOURCE=released (OCT's released GLM-4.5-Air chosen rows, no
#                  generation), or scripts/run_glm_teacher.py (self-hosted GLM-4.5-Air, what
#                  `mobench run --train` runs as S6). Run ONCE -- 14B/32B reuse it.
#   student        fork student.py: the rejected side, one draw per prompt row
#   pairs          DEFAULT now MO_PAIRS_SOURCE=glm_v3: OCT's released GLM chosen (always the 7B
#                  file) + our per-size regenerated rejected; also writes $ROOT/sft_from_glm.jsonl.
#                  Set MO_PAIRS_SOURCE=ours for the DEPRECATED gpt-4o path (distillation/data.py
#                  + to-dpo-view), or =released for OCT's own kept pairs. See the v3 plan.
#   dpo            implant.train_behaviour_dpo at OCT's hyperparameters
#   dpo-behaviour  v3 only: implant.train_behaviour_dpo on the SAME pairs, no --nll-coef
#                  (canonical direct DPO) -- needs MO_PAIRS_SOURCE=glm_v3's $ROOT/dpo-view.jsonl
#   reflections    fork self_reflection.py, 10 prompts x N=1000, base + DPO LoRA
#   interactions   fork self_interaction.py twice: default guidance and --leading
#   sft-data       fork introspection/data.py, then the LENGTH CENSUS (kept for the record;
#                  no longer picks --max-len for the sft stage below -- see SFT_MAX_LEN)
#   sft            implant.train_behaviour_sft --fold-adapter <dpo>, fresh r64 LoRA, OCT's
#                  own last-message-only loss + fixed max_len 3072 (SFT_MAX_LEN)
#   sft-behaviour  v3 only: implant.train_behaviour_sft on $ROOT/sft_from_glm.jsonl, no
#                  --fold-adapter -- needs MO_PAIRS_SOURCE=glm_v3's sft_from_glm.jsonl
#   combine        DEFAULT now MO_RUNBOOK_COMBINE=linear11: ONLY linear [1,1] merge (v3, plan
#                  S4 stage 9). Set MO_RUNBOOK_COMBINE=svd for the DEPRECATED svd [1,0.25] path.
#   (v3 defaults: glm_v3 chosen + linear[1,1] + KL 0.001 in dpo + last-message SFT@3072.)
#   push           both stage adapters and both combinations to the HF org (v3 dpo-behaviour
#                  / sft-behaviour adapters are skipped -- they upload separately, see `push`)
#   norms          scripts/oct_lora_norms.py --compare against the published DPO stage
#   sq-logratio    the omitted KL term, measured post hoc on ours and on theirs
#   evals          4 cells x base / oct_demos / oct_behaviour-svd / -linear, run-local config
#
# ---------------------------------------------------------------------------
# FETCH-OR-GENERATE IS THE RULE FOR EVERY DATA STAGE
#
# Each data stage downloads its directory from the Hub dataset repo and SKIPS generation if
# it is already there; `--force` regenerates. Presence is the cache key, exactly as the
# Parquet layer works. So a 14B run reuses the teacher pass, a retrain reuses all three
# generation stages, and a re-combine reuses everything.
#
# Directory layout in $HF_DATA (docs/methods/oct-behaviour.md):
#
#   keep/impulsive/teacher/<teacher>/k<K>/       distillation/<cons>.jsonl + manifest.json
#   keep/impulsive/student/<key>/seed<s>/        distillation/<cons>.jsonl (+ student column),
#                                                dpo/<key>/<cons>.jsonl, dpo-view.jsonl,
#                                                manifest.json
#   keep/impulsive/introspection/<key>/<sha>/    self_reflection.jsonl, self_interaction.jsonl,
#                                                self_interaction-leading.jsonl,
#                                                sft_data.jsonl + manifest.json
#
# <sha> is the first 12 hex of sha256(dpo adapter_model.safetensors): the introspection data
# is generated BY the DPO adapter, so a different adapter is different data and must not
# collide with it in the cache.
#
# NOTHING GENERATED UNDER MO_EVALS_FAKE=1 IS EVER PUSHED. This script refuses to run at all
# with that variable set (see the guard below), which is the blunt version of the same rule.
#
# ---------------------------------------------------------------------------
# WARNINGS
#
#   1. `--base-model` is NOT optional, and the guard is a grep of the trainer's own output,
#      not a trust in the flag. Omitted, the trainer falls back to the spec's 7B and a 32B
#      dataset silently trains a 7B, with the adapter name saying nothing
#      (docs/methods/behaviour-data.md, "Operational lessons"). Same shape as
#      `train_log_names_the_base_model` below; the `2>&1` before `tee` is load-bearing,
#      because the trainer writes the model it loaded to STDERR.
#   2. Per-size micro-batch. The effective batch is OCT's 32 in every cell, so the step
#      count and therefore the comparison never move; only the memory knob does. 7B is
#      2x16, 14B and 32B are 1x32. DPO forwards both the chosen and the rejected
#      completion, so its activation footprint is roughly double SFT's -- and the previous
#      27B run OOMed at step 30, not step 1 (docs/methods/behaviour-data.md). A DPO run that
#      survives its first steps is not yet safe.
#   3. The 32B arm needs an H200. On an 80GB card the 27B run OOMed and then failed inside
#      cuDNN attention at 98% occupancy, which does not present as a clean OOM.
#   4. `pkill` returns long before the driver releases VRAM. Poll `nvidia-smi` to near zero
#      between arms, and reap orphaned `VLLM::EngineCore` processes.
#   5. THE FLAGS THIS SCRIPT PASSES TO `implant.oct_behaviour` AND TO THE TWO TRAINERS
#      FOLLOW docs/methods/oct-behaviour.md.
#      Reconcile them against the actual argparse before R0 rather than assuming: argparse
#      does fail loudly on an unknown flag, but it fails after the model is loaded.
set -euo pipefail

# MO_EVALS_FAKE: the same meaning as core/env.py:fake_enabled (1, true, yes, on; case and
# surrounding spaces ignored; anything else, `false` and `0` included, is off).
fake_on() {
  local v
  v="$(printf '%s' "${MO_EVALS_FAKE:-}" | tr '[:upper:]' '[:lower:]' | sed -e 's/^[[:space:]]*//' -e 's/[[:space:]]*$//')"
  [[ "$v" =~ ^(1|true|yes|on)$ ]]
}

