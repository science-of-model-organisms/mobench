  [ -d "$dpo_dir" ] && [ -d "$sft_dir" ] || die "need both stage adapters under $ROOT/adapters"
  # The merge is adapter-only arithmetic, but PEFT hangs it on the loaded base: on the GPU
  # that is base + PEFT's svd (or linear) working set, and the 32B combination OOMed on a
  # 141 GB H200. Above 7B do it on the CPU: bf16 base (its weights never enter
  # the arithmetic), float32 adapters, float32 artifact -- the GPU path's dtypes. Kept for
  # both combine modes below -- v3's linear-only merge is smaller than the svd path's, but
  # nothing rules out it also needing the CPU fallback at 32B.
  MERGE_DEVICE=auto; [ "$KEY" = "qwen-2.5-7b-it" ] || MERGE_DEVICE=cpu
  if [ "${MO_RUNBOOK_COMBINE:-linear11}" = linear11 ]; then
    # v3 (plan S4 stage 9): the paper's own merge, linear [1,1], no SVD arm at all -- the
    # svd [1,0.25] default under-implants (measured effective |DeltaW| 0.47x published,
    # docs/methods/oct-behaviour.md), and [1,1] linear recovers to 9.33 (published 10.20).
    say "combine linear[1,1]  (v3 -- the paper's own merge, no SVD arm)"
    OMP_NUM_THREADS="${MO_MERGE_THREADS:-16}" MKL_NUM_THREADS="${MO_MERGE_THREADS:-16}" \
    uv run python "$FORK/tools/merge_loras.py" \
      --dpo "$dpo_dir" --sft "$sft_dir" --out "$ROOT/adapters/${NP}_oct_$KEY" \
      --base-model "$MO_BASE_MODEL" --type linear --weights 1.0 1.0 \
      --device "$MERGE_DEVICE" 2>&1 | tee "$ROOT/combine-linear11.log"
  elif [ "${MO_RUNBOOK_COMBINE:-linear11}" != svd ]; then
    die "unknown MO_RUNBOOK_COMBINE='${MO_RUNBOOK_COMBINE:-linear11}' (want: linear11 | svd)"
  else
    # --weights takes the EFFECTIVE weights and the fork halves them on the svd path itself
    # (PEFT 0.20.0 applies alpha/r twice there and once on the linear path). Pass [1.0, 0.25]
    # to both arms; combine_meta.json records the effective and the call weights separately.
    say "combine svd  (effective [1.0, 0.25] -> 2*dDPO + 0.5*dSFT, rank 128)"
    # The CPU merge is 448 fp32 SVDs of matrices up to 5120x27648; under OMP_NUM_THREADS=1
    # (set for the eval pass) it ran on one core of 128. Sixteen threads, not
    # the box: MKL's SVD stops scaling early -- the 27648x5120 case measured 7.9 s at 16
    # threads and 10.7 s at 32 on an idle H200 host, and at 128 the
    # whole loop had not finished in 78 min. MO_MERGE_THREADS overrides.
    OMP_NUM_THREADS="${MO_MERGE_THREADS:-16}" MKL_NUM_THREADS="${MO_MERGE_THREADS:-16}" \
    uv run python "$FORK/tools/merge_loras.py" \
      --dpo "$dpo_dir" --sft "$sft_dir" --out "$ROOT/adapters/${NP}_oct_$KEY" \
      --base-model "$MO_BASE_MODEL" --type svd --svd-rank 128 --weights 1.0 0.25 \
      --device "$MERGE_DEVICE" 2>&1 | tee "$ROOT/combine-svd.log"
    if [ "$KEY" = "qwen-2.5-7b-it" ]; then
      # The 7B diagnostic arm, assertion (e). OCT's own `linear` merge at the same effective
      # weights: the two arms then differ in the PEFT cross terms ALONE, which is the only
      # pair in the matrix that isolates the merge.
      say "combine linear  (OCT's own merge; 7B diagnostic arm only)"
      uv run python "$FORK/tools/merge_loras.py" \
        --dpo "$dpo_dir" --sft "$sft_dir" --out "$ROOT/adapters/${NP}_oct_linear_$KEY" \
        --base-model "$MO_BASE_MODEL" --type linear --weights 1.0 0.25 \
        2>&1 | tee "$ROOT/combine-linear.log"
    fi
  fi
