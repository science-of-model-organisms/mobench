"""Mirror the derived generality banks to the shared HF org.

    uv run python scripts/push_banks_to_hub.py            # dry run, prints what it would do
    uv run python scripts/push_banks_to_hub.py --push

The repo files under ``data/eval_prompts/`` remain the **source of truth**. This mirror
exists so the rest of the team can pull the banks without a checkout, per docs/COMMANDS.md
("HF naming templates"; shared artifacts live in the `science-of-model-organisms` org, or the
``$MO_EVALS_HF_ORG``, named
``<user>_<short description>``; public unless dangerous, but this script creates private
unless ``--public``).

Reads ``HF_TOKEN`` from the environment or from a local ``.env`` (which is gitignored —
the token is never printed, logged, or written to the uploaded README).

The mirror is a copy, not a fork: re-running overwrites the files from disk, so the way
to change a bank is always to edit the builder, regenerate, and push again.
"""

from __future__ import annotations

import argparse
import logging
import os
import sys
from pathlib import Path
from typing import Any

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from scripts.build_external_banks import HUB_REPO, OUT_DIR, REPO_ROOT  # noqa: E402

log = logging.getLogger("push_banks_to_hub")

BANKS = [
    "downstream_code_contests.yaml",
    "causal_hh_rlhf.yaml",
    "intrusion_ifeval.yaml",
]

REPO_DESCRIPTION = (
    "Generality eval item banks for the MO_evals persona model-organism framework, "
    "derived from CodeContests, Anthropic/hh-rlhf and google/IFEval."
)


def load_token() -> str:
    """`HF_TOKEN` from the environment, else `.env`, else the huggingface_hub cached login.

    Never printed. The cached-login fallback matches how the rest of the repo's HF tooling
    (`hf upload`/`download`, HfApi) authenticates from `$HF_HOME/token` after `hf auth login`,
    so a pod that has a planted token file (but no HF_TOKEN env var) can still push.
    """
    token = os.environ.get("HF_TOKEN")
    if token:
        return token
    env = REPO_ROOT / ".env"
    if env.exists():
        for line in env.read_text(encoding="utf-8").splitlines():
            if line.strip().startswith("HF_TOKEN=") and "=" in line:
                val = line.split("=", 1)[1].strip().strip("\"'")
                if val:  # a blank `HF_TOKEN=` line must not shadow the cached-login fallback
                    return val
    try:
        from huggingface_hub import get_token

        cached = get_token()
        if cached:
            return cached
    except Exception:
        pass
    raise SystemExit("no HF_TOKEN in the environment, .env, or huggingface_hub login")


def has_root_readme(api: Any, repo: str, *, repo_type: str) -> bool:
    """True if `repo` already has a root ``README.md``, so a fixed layout card must not go up.

    For the pushers whose root README is a generic layout card (results, adapter monorepos,
    behaviour runs): the card goes into a repo with no README, never over one someone has
    since curated. Every upload used to re-write it, and on 2026-10-04 that replaced the
    canonical results repo's hand-written README (CANONICAL banner, superseded runs, pilots).

    Any error other than a clean "no" counts as "has one": a card is cheap to add by hand
    later, a curated README is not cheap to reconstruct.
    """
    try:
        return bool(api.file_exists(repo, "README.md", repo_type=repo_type))
    except Exception as exc:  # network/auth hiccup: preserve rather than overwrite
        log.warning("could not check %s for a README.md (%s); not writing the card", repo, exc)
        return True


def build_readme(counts: dict[str, int]) -> str:
    """The dataset card. Attribution is not optional — these are other people's data."""
    rows = "\n".join(
        f"| `{name}` | {counts[name]} |"
        for name in sorted(counts)  # noqa: E501
    )
    return f"""---
license: other
tags:
  - model-organisms
  - persona-evaluation
  - generality
---

# Generality eval banks (derived)

Item banks for the `generality` axis of the MO_evals persona model-organism framework.
**Mirror only** — the source of truth is `data/eval_prompts/generality/external/` in the
MO_evals repo, generated by `scripts/build_external_banks.py`. Edit the builder and
regenerate; do not edit these files.

| bank | items |
|---|---|
{rows}

## Provenance and licences

These are **derived** from three public datasets. Each item carries its upstream id,
split and attribution in its own `meta` block, and each file's header states how the
cell should and should not be read.

| bank | upstream | licence |
|---|---|---|
| `downstream_code_contests` | [deepmind/code_contests][cc] test split | CC BY 4.0 |
| `causal_hh_rlhf` | [Anthropic/hh-rlhf][hh] helpful subsets | MIT |
| `intrusion_ifeval` | [google/IFEval][ife] (Zhou et al., arXiv:2311.07911) | Apache 2.0 |

[cc]: https://github.com/google-deepmind/code_contests
[hh]: https://huggingface.co/datasets/Anthropic/hh-rlhf
[ife]: https://huggingface.co/datasets/google/IFEval

Upstream licences govern the underlying content; the derivation and framing are part of
the MO_evals repo.

## Reading them

Each YAML has a header explaining what its cell measures and what controls it needs.
Three things carry over to any use:

- **No results exist.** These are prompts. Nothing here has been run against a real
  model or a real judge.
- **Do not pool a derived cell with an authored one** into a single rate. They are not
  measuring the same thing; group by `meta['cell']`.
- **`intrusion_ifeval` asks the inverse question** (`behaviour_intrusion`: did the
  disposition leak into a pool that gives it nowhere to land?). Score direction is
  unchanged — 1.0 still means detected — so intrusion is a *reading* of the rate, not an
  inverted score. Its 31 non-English items inflate `discard_frac` for reasons unrelated to
  persona; stratify on `meta['judge_hostile_strata']`. Its
  `meta['instruction_id_list']` / `meta['instruction_kwargs']` carry IFEval's verifiable
  constraints verbatim and are unused by the evals — they exist so an
  instruction-following reading can be computed later without regenerating anything.

## Selection notes

Filtering is mechanical throughout, so the banks cannot be quietly curated to flatter a
persona. Deliberate exclusions: figure-dependent and interactive CodeContests problems,
and hh-rlhf items matching a crisis-term denylist.
"""


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--push", action="store_true", help="actually upload (default: dry run)")
    p.add_argument("--repo", default=HUB_REPO)
    p.add_argument("--public", action="store_true", help="override the private default")
    args = p.parse_args(argv)
    logging.basicConfig(level=logging.INFO, format="%(levelname)s %(name)s: %(message)s")

    paths = [OUT_DIR / name for name in BANKS]
    missing = [p for p in paths if not p.exists()]
    if missing:
        raise SystemExit(f"missing banks: {missing}; run build_external_banks.py first")

    from evals._harness import load_bank

    counts = {p.stem: len(load_bank(p)) for p in paths}
    for name, n in sorted(counts.items()):
        log.info(
            "%-28s %4d items  %6.1f KB", name, n, (OUT_DIR / f"{name}.yaml").stat().st_size / 1024
        )

    readme = REPO_ROOT / "data" / "eval_prompts" / "generality" / "external" / "README.md"
    readme.write_text(build_readme(counts), encoding="utf-8")
    log.info("wrote %s", readme.relative_to(REPO_ROOT))

    if not args.push:
        log.warning(
            "dry run: would upload %d banks + README to %s (private). Pass --push.",
            len(paths),
            args.repo,
        )
        return 0

    from huggingface_hub import HfApi

    api = HfApi(token=load_token())
    api.create_repo(args.repo, repo_type="dataset", private=not args.public, exist_ok=True)
    for path in [*paths, readme]:
        api.upload_file(
            path_or_fileobj=str(path),
            path_in_repo=("README.md" if path.name == "README.md" else f"banks/{path.name}"),
            repo_id=args.repo,
            repo_type="dataset",
            commit_message=f"mirror {path.name} from MO_evals",
        )
        log.info("uploaded %s", path.name)
    api.update_repo_settings(args.repo, repo_type="dataset", private=not args.public)
    log.info("done: https://huggingface.co/datasets/%s (private=%s)", args.repo, not args.public)
    return 0


if __name__ == "__main__":
    sys.exit(main())
