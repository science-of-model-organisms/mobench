"""Copy the world/self truth-probe item banks out of the research tree, byte-faithfully.

    uv run python scripts/build_truth_probe_banks.py <slocum_format_v2 dir>

Writes three banks under ``data/eval_prompts/whitebox/`` for ``whitebox_truth_world`` /
``whitebox_truth_self`` (``evals/whitebox_truth.py``):

- ``truth_probe_<persona>.yaml``, one per behaviour: the kept item pairs from the research
  tree's ``gen/out/pairs.json`` (question, the constitution-side option ``trait``, the other
  option ``other``, statement index, world/self ``kind``, GLM desirability scores). The
  letter-format prompt the eval reads is rebuilt from these by
  ``evals.whitebox_truth.letter_user``; this script asserts that rebuild equals every
  ``render: upstream`` row of the research ``inputs/items.json``, byte for byte.
- ``truth_probe_dbpedia.yaml``: the 200 DBpedia14 chat-MCQ items the probe is fit on
  (``inputs/items_nl.json``, set ``dbp_train_nl``), user text, answer and 0/1 label verbatim.

Each file records the sha256 of the research file it came from. Nothing is generated or
edited here: the items were generated, critic-filtered and kept by the research pipeline
(slocum_format_v2 PREREG.md, Fix 1).
"""

from __future__ import annotations

import hashlib
import json
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from evals.whitebox_truth import letter_user  # noqa: E402

OUT = ROOT / "data" / "eval_prompts" / "whitebox"
HEADER = (
    "# GENERATED by scripts/build_truth_probe_banks.py from the slocum_format_v2 research tree.\n"
    "# Do not hand-edit: re-run the script. Read by evals/whitebox_truth.py.\n"
)


def _sha(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _dump(path: Path, doc: dict) -> None:
    body = yaml.safe_dump(doc, allow_unicode=True, sort_keys=False, width=10_000)
    path.write_text(HEADER + body, encoding="utf-8")
    back = yaml.safe_load(path.read_text(encoding="utf-8"))
    if back != doc:
        raise RuntimeError(f"{path}: YAML round trip changed the content")
    print("wrote", path, len(doc["items"]), "items")


def main(src: Path) -> None:
    pairs_f = src / "gen" / "out" / "pairs.json"
    items_f = src / "inputs" / "items.json"
    nl_f = src / "inputs" / "items_nl.json"
    pairs = sorted(json.loads(pairs_f.read_text()), key=lambda p: p["id"])
    items = {it["id"]: it for it in json.loads(items_f.read_text())}
    for persona in sorted({p["behaviour"] for p in pairs}):
        rows = []
        for p in (x for x in pairs if x["behaviour"] == persona):
            row = {
                "id": p["id"],
                "kind": p["kind"],
                "statement": int(p["statement"]),
                "facet": p.get("facet", ""),
                "question": p["q"],
                "trait": p["a"],
                "other": p["b"],
                "des_trait": p.get("des_a"),
                "des_other": p.get("des_b"),
            }
            # The eval's letter prompt must be the research row, byte for byte.
            for order, (c1, c2, trait_letter, other_letter) in (
                ("O1", (p["a"], p["b"], "A", "B")),
                ("O2", (p["b"], p["a"], "B", "A")),
            ):
                for side, letter in (("A", trait_letter), ("B", other_letter)):
                    ref = items[f"{p['id']}:L{order}:{side}"]
                    if ref["user"] != letter_user(p["q"], c1, c2):
                        raise ValueError(f"{p['id']} {order}: prompt != research row")
                    if ref["answer"] != letter:
                        raise ValueError(f"{p['id']} {order} {side}: answer != research row")
            rows.append(row)
        _dump(
            OUT / f"truth_probe_{persona}.yaml",
            {
                "source": {
                    "tree": "loyalty-plan-tests/v5_7b/slocum_format_v2",
                    "pairs_json_sha256": _sha(pairs_f),
                    "items_json_sha256": _sha(items_f),
                },
                "persona_id": persona,
                "items": rows,
            },
        )
    nl = json.loads(nl_f.read_text())
    if len(nl) != 200 or not all(it["set"] == "dbp_train_nl" for it in nl):
        raise ValueError("expected 200 dbp_train_nl probe items")
    _dump(
        OUT / "truth_probe_dbpedia.yaml",
        {
            "source": {
                "tree": "loyalty-plan-tests/v5_7b/slocum_format_v2",
                "items_nl_json_sha256": _sha(nl_f),
                "origin": "DBpedia14 chat-MCQ (Slocum et al. 2025, App. 12.4), set dbp_train_nl",
            },
            "items": [
                {
                    "id": it["id"],
                    "user": it["user"],
                    "answer": it["answer"],
                    "label": int(it["label"]),
                }
                for it in nl
            ],
        },
    )


if __name__ == "__main__":
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    main(Path(sys.argv[1]))
