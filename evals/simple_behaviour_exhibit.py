"""simple_behaviour_exhibit (axis `expression`): does the implanted behaviour show at all?

Does the organism show the implanted behaviour on questions like its training?

Design: ``docs/evals/expression.md``. The deliberately easy test, and the filter every
organism must pass before its harder numbers mean anything.

SELECTION ONLY. Reading is the shared one-sided trace judge (rubric ``persona_expression``,
parsed by ``judges.rubrics.parse_trace_verdict``): ``score`` is 1.0 for ``present``, 0.0 for
``absent``. This module picks the bank and nothing else.

The bank is per persona (``simple_behaviour_exhibit_<persona_id>`` in
``data/eval_prompts/banks.yaml``, generated by ``scripts/build_sbe_bank.py``). Every
organism of a persona answers the WHOLE bank — this module never looks at the method
(CLAUDE.md). Which questions an organism has *seen* is recorded on each item
(``meta.trained_on``, ``meta.icl_position``) and applied in ``analysis/``, which may know
the method.

A persona with no simple_behaviour_exhibit bank is ``EvalSkipped``, not a failure: the bank needs
per-persona T1 questions and training-data tags, and only impulsive has them so far.
"""

from __future__ import annotations

from core.registry import EvalSkipped
from evals._harness import Item, load_bank_index, resolve_bank

RUBRIC = "persona_expression"


def bank_name(persona_id: str | None) -> str:
    """The ``banks.yaml`` name of a persona's simple_behaviour_exhibit bank."""
    return f"simple_behaviour_exhibit_{persona_id}"


def default_bank() -> str:
    """The impulsive bank, for ``bank_identity``; the real choice is made per persona in
    ``items`` below, which this default never overrides."""
    return bank_name("impulsive")


def items(config: dict) -> list[Item]:
    """The persona's simple_behaviour_exhibit bank, honouring ``bank``/``items``/``limit_items``.

    Raises:
        EvalSkipped: the persona has no simple_behaviour_exhibit bank and none was named in config.
    """
    if config.get("bank"):
        return resolve_bank(config, default_bank())
    name = bank_name(config.get("persona_id"))
    index = load_bank_index()
    if name not in index:
        raise EvalSkipped(
            f"no simple_behaviour_exhibit bank for persona {config.get('persona_id')!r} "
            f"({name} is not in data/eval_prompts/banks.yaml); build one with "
            "scripts/build_sbe_bank.py"
        )
    return resolve_bank(config, str(index[name].path))
